#!/usr/bin/env python3
"""Generate vectors.hirsel from RFC 3711/7714 and libSRTP fd08747f."""
from contextlib import redirect_stdout
import hmac
from io import StringIO
import struct

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

CM = bytes.fromhex("e1f97a0d3e018be0d64fa32c06de41390ec675ad498afeebb6960b3aabe6")
GCM = bytes(range(16)) + bytes(range(0xa0, 0xac))
GCM256 = bytes(range(32)) + bytes(range(0xa0, 0xac))
LIB_RTCP = bytes.fromhex("81c8000bcafebabe") + bytes([0xab]) * 16


def ctr(key, iv, data):
    return Cipher(algorithms.AES(key), modes.CTR(iv)).encryptor().update(data)


def protect(profile, master, header, body, ssrc, index, *, rtcp=False, encrypt=True):
    width = 32 if profile == "gcm256" else 16
    salt_width = 14 if profile == "cm" else 12
    key, master_salt = master[:width], master[width:]
    label = 3 if rtcp else 0

    def derive(purpose, size):
        iv = bytearray(master_salt.ljust(16, b"\0"))
        iv[7] ^= label + purpose
        return ctr(key, iv, bytes(size))

    payload_key = derive(0, width)
    salt = derive(2, salt_width)
    if rtcp:
        trailer = struct.pack(">I", (int(encrypt) << 31) | index)
    else:
        trailer = struct.pack(">I", index >> 16)

    if profile == "cm":
        counter = int.from_bytes(salt + b"\0\0", "big") ^ (ssrc << 64) ^ (index << 16)
        cipher = ctr(payload_key, counter.to_bytes(16, "big"), body) if encrypt else body
        tag = hmac.digest(derive(1, 20), header + cipher + trailer, "sha1")[:10]
        return header + cipher + (trailer if rtcp else b"") + tag

    if rtcp:
        nonce = struct.pack(">HIHI", 0, ssrc, 0, index)
        aad = header + (b"" if encrypt else body) + trailer
    else:
        nonce = struct.pack(">HI", 0, ssrc) + index.to_bytes(6, "big")
        aad = header
    iv = bytes(a ^ b for a, b in zip(salt, nonce, strict=True))
    cipher = AESGCM(payload_key).encrypt(iv, body if encrypt else b"", aad)
    return header + (body if not encrypt else b"") + cipher + (trailer if rtcp else b"")


def rtp_header(ssrc, seq, first=0x80, extension=b""):
    return struct.pack(">BBHII", first, 96, seq & 0xffff, 1, ssrc) + extension


def rtp(profile, master, ssrc, index, body=b"abc", first=0x80, extension=b""):
    return protect(profile, master, rtp_header(ssrc, index, first, extension), body, ssrc, index)


def rtcp(profile, master, compound, index, encrypt=True):
    ssrc = int.from_bytes(compound[4:8], "big")
    return protect(profile, master, compound[:8], compound[8:], ssrc, index, rtcp=True, encrypt=encrypt)


def hirsel(name, data):
    print(f"fn {name}() -> Bytes {{")
    if len(data) <= 110:
        print(f'    unhex("{data.hex()}")')
    else:
        print(f"    let mut out: Bytes = list.with_capacity({len(data)})")
        for offset in range(0, len(data), 96):
            print(f'    list.append(mut out, unhex("{data[offset:offset + 96].hex()}"))')
        print("    take out")
    print("}\n")


def main():
    print("// Generated by python3 oracle.py. Oracles use Python cryptography and hmac.")
    for label, master in [("cm", CM), ("gcm", GCM), ("gcm256", GCM256)]:
        hirsel(f"master_{label}", master)

    one_byte = bytes.fromhex("01020304bede000110aa0000")
    two_byte = bytes(range(60)) + bytes.fromhex("010000010102aabb")
    header_cases = [
        ("cm", CM, 0x80, b"", b"abc"),
        ("gcm", GCM, 0x91, one_byte, b"abc"),
        ("gcm256", GCM256, 0xbf, two_byte, b"abc\x00\x02"),
    ]
    for case, (profile, master, first, extension, body) in enumerate(header_cases):
        hirsel(f"header_plain_{case}", rtp_header(1, 10, first, extension) + body)
        hirsel(f"header_wire_{case}", rtp(profile, master, 1, 10, body, first, extension))

    hirsel("rollover_packets", b"".join(rtp("cm", CM, 1, i) for i in range(65534, 65538)))
    hirsel("roc_five_packet", rtp("cm", CM, 1, (5 << 16) + 7))
    hirsel("replay_rtp", b"".join(rtp("gcm", GCM, 1, i)[12:] for i in range(202)))
    hirsel("replay_rtp_far", rtp("gcm", GCM, 1, 10000))
    hirsel("replay_rtp_second", b"".join(rtp("gcm", GCM, 2, i) for i in range(8)))
    hirsel("replay_rtp_third", rtp("gcm", GCM, 3, 0))
    compound = bytes.fromhex("80c9000200000002") + b"abcd"
    hirsel("replay_rtcp", b"".join(rtcp("gcm", GCM, compound, i) for i in range(7)))
    hirsel("replay_rtcp_far", rtcp("gcm", GCM, compound, 10000))

    hirsel("rtcp_plain", LIB_RTCP)
    lib_cm = bytes.fromhex(
        "81c8000bcafebabe7128035be487b9bdbef89041f977a5a880000001993e08cd54d6c1230798"
    )
    lib_gcm = bytes.fromhex(
        "81c8000bcafebabec98b8b5df0392a55852b6c21ac8e7025c52c6fbea2b3b446ea31123ba88ce61e80000001"
    )
    # The libSRTP fixtures start SRTCP at 1. The session default starts at 0.
    assert rtcp("cm", CM, LIB_RTCP, 1) == lib_cm
    assert rtcp("gcm", GCM, LIB_RTCP, 1) == lib_gcm
    for label, master, expected in [("cm", CM, lib_cm), ("gcm", GCM, lib_gcm)]:
        hirsel(f"lib_rtcp_{label}", expected)
        hirsel(f"clear_rtcp_{label}", rtcp(label, master, LIB_RTCP, 2, encrypt=False))
    hirsel("last_rtcp", rtcp("gcm", GCM, LIB_RTCP, (1 << 31) - 1))
    hirsel("first_rtcp", rtcp("gcm", GCM, LIB_RTCP, 0))
    hirsel("last_rtp", rtp("gcm", GCM, 3, (1 << 48) - 1))

    payload = bytes(i % 251 for i in range(1000))
    for i in range(3):
        key = bytes(range(i, 16 + i)) + GCM[16:]
        hirsel(f"fan_key_{i}", key)
        hirsel(f"fan_wire_{i}", rtp("gcm", key, 20 + i, 100 + i, payload))


if __name__ == "__main__":
    output = StringIO()
    with redirect_stdout(output):
        main()
    print(output.getvalue().rstrip())
