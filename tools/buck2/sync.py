def corpus_hash(path: str) -> int:
    """hirsel-cli-args Shard::holds, including its u64 wrap."""
    value = 0xcbf29ce484222325
    for byte in path.encode():
        value = ((value ^ byte) * 0x100000001b3) & ((1 << 64) - 1)
    return value


