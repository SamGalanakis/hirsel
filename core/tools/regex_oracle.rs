fn inline(out: &mut String, name: &str, ty: &str, values: &[u64]) {
    writeln!(out, "const {name}: Inline[{ty}, {}] =[", values.len()).unwrap();
    for row in values.chunks(12) {
        out.push_str("    ");
        for value in row {
            write!(out, "{value}, ").unwrap();
        }
        out.pop();
        out.push('\n');
    }
    out.push_str("]\n\n");
}

fn char_property(mut f: impl FnMut(char) -> bool) -> Vec<(char, char)> {
    let mut ranges = Vec::<(char, char)>::new();
    for c in (0..=0x10ffff).filter_map(char::from_u32).filter(|&c| f(c)) {
        if let Some((_, hi)) = ranges.last_mut()
            && (*hi as u32) + 1 == c as u32
        {
            *hi = c;
        } else {
            ranges.push((c, c));
        }
    }
    ranges
}

fn alias_table(out: &mut String, rows: impl IntoIterator<Item = (u64, &'static str, u64)>) {
    let mut aliases = Vec::new();
    let mut words = Vec::new();
    for (property, alias, value) in rows {
        assert!(alias.len() <= 64);
        words.extend([property, aliases.len() as u64, alias.len() as u64, value]);
        aliases.extend(alias.bytes().map(u64::from));
    }
    inline(out, "ALIAS_TEXT", "u8", &aliases);
    inline(out, "ALIASES", "u32", &words);
    writeln!(out, "const ALIAS_COUNT: u64 = {}\n", words.len() / 4).unwrap();
}

fn tables() -> String {
    let mut out = TABLE_MARKER.to_owned();
    out.push_str(
        "// Perl classes, folds, and property aliases are from regex-syntax's Unicode tables.\n",
    );
    out.push_str(
        "// Unicode data is licensed under Unicode-3.0 (https://www.unicode.org/license.txt).\n\n",
    );
    let alphabetic = char_property(char::is_alphabetic);
    let numeric = char_property(char::is_numeric);
    let mut ranges = Vec::new();
    for (name, table) in [
        ("DECIMAL", decimal::BY_NAME[0].1),
        ("SPACE", space::BY_NAME[0].1),
        ("WORD", word::PERL_WORD),
        ("NAME_START", alphabetic.as_slice()),
        ("NAME_CONTINUE", numeric.as_slice()),
    ] {
        let lo = ranges.len() / 2;
        ranges.extend(table.iter().flat_map(|&(lo, hi)| [lo as u64, hi as u64]));
        writeln!(out, "const {name}_LO: u64 = {lo}").unwrap();
        writeln!(out, "const {name}_HI: u64 = {}\n", ranges.len() / 2).unwrap();
    }
    inline(&mut out, "UNICODE_RANGES", "u32", &ranges);
    let words: Vec<_> = folds::CASE_FOLDING_SIMPLE
        .iter()
        .flat_map(|&(from, targets)| targets.iter().map(move |&to| [from as u64, to as u64]))
        .flatten()
        .collect();
    inline(&mut out, "CASE_FOLD", "u32", &words);
    writeln!(out, "const FOLD_COUNT: u64 = {}\n", words.len() / 2).unwrap();
    let properties: BTreeSet<_> = names::PROPERTY_NAMES
        .iter()
        .map(|&(_, name)| name)
        .chain(values::PROPERTY_VALUES.iter().map(|&(name, _)| name))
        .collect();
    let mut codes = BTreeMap::from([("General_Category", 1), ("White_Space", 2), ("Age", 3)]);
    for p in properties {
        let code = codes.len() as u64 + 1;
        codes.entry(p).or_insert(code);
    }
    let mut rows: Vec<_> = values::PROPERTY_VALUES
        .iter()
        .flat_map(|&(name, aliases)| {
            let property = codes[name];
            aliases.iter().map(move |&(alias, canonical)| {
                (
                    property,
                    alias,
                    if canonical == "Decimal_Number" { 1 } else { 2 },
                )
            })
        })
        .collect();
    rows.extend([(1, "any", 2), (1, "ascii", 2), (1, "assigned", 2)]);
    rows.extend(
        names::PROPERTY_NAMES
            .iter()
            .map(|&(alias, name)| (0, alias, codes[name])),
    );
    rows.sort_unstable();
    alias_table(&mut out, rows);
    out.pop();
    out
}

fn formatted(formatter: &Path, source: &str) -> String {
    use std::io::Write as _;

    let path =
        std::env::temp_dir().join(format!("hirsel-regex-oracle-{}.hirsel", std::process::id()));
    let mut input = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .unwrap();
    input.write_all(source.as_bytes()).unwrap();
    drop(input);
    let result = std::process::Command::new(formatter).arg(&path).output();
    std::fs::remove_file(path).unwrap();
    let result = result.unwrap();
    assert!(
        result.status.success(),
        "{}",
        String::from_utf8_lossy(&result.stderr)
    );
    String::from_utf8(result.stdout).unwrap()
}

fn observe(path: &Path, expected: String, write: bool) -> bool {
    if write {
        std::fs::write(path, expected).unwrap();
        return true;
    }
    if std::fs::read_to_string(path).as_deref().ok() == Some(&expected) {
        return true;
    }
    eprintln!("{} is stale", path.display());
    false
}

fn main() -> std::process::ExitCode {
    let options: Vec<_> = std::env::args_os().skip(1).collect();
    let [mode, executable] = options.as_slice() else {
        eprintln!("usage: regex_oracle --check | --write FORMATTER");
        return std::process::ExitCode::FAILURE;
    };
    let write = match mode.to_str() {
        Some("--write") => true,
        Some("--check") => false,
        _ => {
            eprintln!("usage: regex_oracle --check | --write FORMATTER");
            return std::process::ExitCode::FAILURE;
        }
    };
    let formatter = Path::new(executable);
    let proc = Path::new("core/std/regex.hirsel");
    let source = std::fs::read_to_string(proc).unwrap();
    let manual = source
        .split_once(TABLE_MARKER)
        .map_or(source.as_str(), |(prefix, _)| prefix);
    let source_ok = observe(
        proc,
        formatted(formatter, &format!("{manual}{}", tables())),
        write,
    );
    let corpus_ok = observe(
        Path::new("core/std/tests/regex_corpus.hirsel"),
        formatted(formatter, &corpus()),
        write,
    );
    if source_ok && corpus_ok {
        std::process::ExitCode::SUCCESS
    } else {
        std::process::ExitCode::FAILURE
    }
}
