#!/usr/bin/env python3
"""Freeze and verify the current-format Directory + Bucket Store corpus (T7).

Only formats still claimed by `DISK_FORMAT` are kept (no-shims policy).
Each format-touching bump refreezes the corpus and deletes retired formats.
"""
import argparse
import base64
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
from std_native import ROOT
from store_tests import inputs

STORE_DIR = ROOT / 'core/programs/store'
CORPUS_ROOT = STORE_DIR / 'corpus'
FORMAT_PATTERN = re.compile(r'^pub const DISK_FORMAT: u64 = ([0-9]+)$', re.M)


def current_format(root=ROOT):
    text = (root / 'core/programs/store/store-format.hirsel').read_text(encoding='utf-8')
    match = FORMAT_PATTERN.search(text)
    if match is None:
        raise ValueError('pub const DISK_FORMAT not found in store-format.hirsel')
    return int(match[1])


def quote_hirsel_string(value):
    escaped = (value.replace('\\', '\\\\')
               .replace('"', '\\"')
               .replace('\n', '\\n')
               .replace('\r', '\\r')
               .replace('\t', '\\t'))
    return f'"{escaped}"'


def render_fixture_module(fmt, dir_files, bucket_objects, dir_dump, bucket_dump):
    lines = [
        f'// Generated by core/tools/store_freeze_corpus.py for Format {fmt}; do not hand-edit.',
        'fn corpus_format_version() -> u64 {',
        f'    {fmt}u64',
        '}',
        '',
        'fn corpus_directory_dump() -> String {',
        f'    {quote_hirsel_string(dir_dump)}',
        '}',
        '',
        'fn corpus_bucket_dump() -> String {',
        f'    {quote_hirsel_string(bucket_dump)}',
        '}',
        '',
        'fn corpus_directory_files() -> List[(String, Bytes)] {',
        f'    let mut out: List[(String, Bytes)] = list.with_capacity({len(dir_files)}u64)',
    ]
    for name, raw in dir_files:
        encoded = base64.b64encode(raw).decode('ascii')
        lines.append(f'    list.push(mut out, (string.from({quote_hirsel_string(name)}), corpus_decode_b64(b"{encoded}")))')
    lines += [
        '    take out',
        '}',
        '',
        'fn corpus_bucket_objects() -> List[(String, Bytes)] {',
        f'    let mut out: List[(String, Bytes)] = list.with_capacity({len(bucket_objects)}u64)',
    ]
    for key, raw in bucket_objects:
        encoded = base64.b64encode(raw).decode('ascii')
        lines.append(f'    list.push(mut out, (string.from({quote_hirsel_string(key)}), corpus_decode_b64(b"{encoded}")))')
    lines += [
        '    take out',
        '}',
        '',
    ]
    return '\n'.join(lines)


def load_frozen_dir(corpus_dir):
    directory = corpus_dir / 'directory'
    dir_files = sorted(
        ((path.name, path.read_bytes()) for path in directory.iterdir()
         if path.is_file() and path.name != 'LOCK'),
        key=lambda item: item[0],
    )
    bucket_dir = corpus_dir / 'bucket'
    manifest_lines = (bucket_dir / 'manifest.txt').read_text(encoding='utf-8').splitlines()
    bucket_objects = []
    for line in manifest_lines:
        if not line:
            continue
        fname, key = line.split('\t', 1)
        bucket_objects.append((key, (bucket_dir / fname).read_bytes()))
    bucket_objects.sort(key=lambda item: item[0])
    dir_dump = (corpus_dir / 'directory.dump').read_text(encoding='utf-8')
    bucket_dump = (corpus_dir / 'bucket.dump').read_text(encoding='utf-8')
    return dir_files, bucket_objects, dir_dump, bucket_dump


def update_fixture_source(root, fmt):
    manifest_path = root / 'core/programs/store/hirsel.hcfg'
    text = manifest_path.read_text(encoding='utf-8')
    target = f'("store_corpus_format{fmt}.hirsel", "store")'
    replaced, count = re.subn(r'\("store_corpus_format[0-9]+\.hirsel", "store"\)', target, text)
    if count != 1:
        raise ValueError(f'{manifest_path}: expected one store_corpus_format*.hirsel entry, found {count}')
    if replaced != text:
        manifest_path.write_text(replaced, encoding='utf-8')


def freeze(args):
    root = args.root.resolve()
    fmt = current_format(root)
    with tempfile.TemporaryDirectory(prefix='hirsel-freeze-corpus-') as tmp:
        work = Path(tmp)
        dir_out = work / 'directory'
        bucket_out = work / 'bucket'
        meta_out = work / 'meta'
        for d in (dir_out, bucket_out, meta_out):
            d.mkdir()
        manifest = work / 'inputs.json'
        manifest.write_text(json.dumps(inputs(root, tests=True)), encoding='utf-8')
        exe = work / 'freeze'
        cmd = [
            str(args.compiler.resolve()), 'build',
            '--inputs', str(manifest),
            '--source-core', '--source-std',
            '--entry', 'store@1/store/corpus_freeze_main',
            '--backend', args.backend,
            '--runtime', str(args.runtime.resolve()),
            '--store', str(work / 'objects'),
            '--limit', str(256 * 1024 * 1024),
            '--dir', str(dir_out),
            '--dir', str(bucket_out),
            '--dir', str(meta_out),
            '--grant', 'Clock',
            '--grant', 'Random',
            '--grant', 'Tasks',
            '--grant', 'Stdout',
            '-o', str(exe), '--json',
        ]
        if args.cc:
            cmd += ['--cc', str(args.cc.resolve())]
        env = dict(os.environ)
        llvm = Path(env.get('LLVM_SYS_231_PREFIX', root / 'tools/buck2/toolchains/llvm-files'))
        if (llvm / 'lib').is_dir():
            env['LD_LIBRARY_PATH'] = str(llvm / 'lib') + ':' + env.get('LD_LIBRARY_PATH', '')
        built = subprocess.run(cmd, env=env, capture_output=True, text=True)
        if built.returncode:
            raise RuntimeError(f'freeze build failed ({built.returncode}):\n{built.stdout}\n{built.stderr}')
        report = json.loads(built.stdout)
        if not report.get('accepted') or not report.get('native', {}).get('linked'):
            raise RuntimeError(f'freeze build rejected:\n{built.stdout}')
        ran = subprocess.run([str(exe)], env=env, capture_output=True, text=True, timeout=300)
        if ran.returncode:
            raise RuntimeError(f'freeze run failed ({ran.returncode}):\n{ran.stdout}\n{ran.stderr}')

        # Prune any retired format copies (no-shims policy).
        corpus_root = root / 'core/programs/store/corpus'
        corpus_root.mkdir(parents=True, exist_ok=True)
        for existing in list(corpus_root.iterdir()):
            if existing.is_dir() and existing.name.startswith('format-'):
                shutil.rmtree(existing)
        for existing in (root / 'core/programs/store').glob('store_corpus_format*.hirsel'):
            existing.unlink()

        target = corpus_root / f'format-{fmt}'
        (target / 'directory').mkdir(parents=True)
        (target / 'bucket').mkdir(parents=True)
        for path in sorted(dir_out.iterdir()):
            if path.is_file() and path.name != 'LOCK':
                dst = target / 'directory' / path.name
                shutil.copyfile(path, dst)
                dst.chmod(0o644)
        for path in sorted(bucket_out.iterdir()):
            if path.is_file():
                dst = target / 'bucket' / path.name
                shutil.copyfile(path, dst)
                dst.chmod(0o644)
        for src, dst in (
            (meta_out / 'bucket.manifest', target / 'bucket/manifest.txt'),
            (meta_out / 'directory.dump', target / 'directory.dump'),
            (meta_out / 'bucket.dump', target / 'bucket.dump'),
        ):
            shutil.copyfile(src, dst)
            dst.chmod(0o644)

        dir_files, bucket_objects, dir_dump, bucket_dump = load_frozen_dir(target)
        fixture_path = root / f'core/programs/store/store_corpus_format{fmt}.hirsel'
        fixture_path.write_text(
            render_fixture_module(fmt, dir_files, bucket_objects, dir_dump, bucket_dump),
            encoding='utf-8',
        )
        update_fixture_source(root, fmt)
        dir_bytes = sum(len(raw) for _, raw in dir_files)
        bucket_bytes = sum(len(raw) for _, raw in bucket_objects)
        print(
            f'froze format-{fmt}: {len(dir_files)} directory files ({dir_bytes} B), '
            f'{len(bucket_objects)} bucket objects ({bucket_bytes} B) -> {target}',
            flush=True,
        )
    return 0


def check(args):
    root = args.root.resolve()
    fmt = current_format(root)
    corpus_root = root / 'core/programs/store/corpus'
    expected_dir = corpus_root / f'format-{fmt}'
    if not expected_dir.is_dir():
        print(f'missing frozen corpus for current format {fmt}: {expected_dir}', file=sys.stderr)
        return 1
    stale = [p.name for p in corpus_root.iterdir() if p.name != f'format-{fmt}']
    if stale:
        print(f'stale retired format copies present (no-shims policy): {stale}', file=sys.stderr)
        return 1
    stale_mods = [p.name for p in (root / 'core/programs/store').glob('store_corpus_format*.hirsel')
                  if p.name != f'store_corpus_format{fmt}.hirsel']
    if stale_mods:
        print(f'stale retired corpus modules present: {stale_mods}', file=sys.stderr)
        return 1
    dir_files, bucket_objects, dir_dump, bucket_dump = load_frozen_dir(expected_dir)
    want = render_fixture_module(fmt, dir_files, bucket_objects, dir_dump, bucket_dump)
    fixture_path = root / f'core/programs/store/store_corpus_format{fmt}.hirsel'
    got = fixture_path.read_text(encoding='utf-8') if fixture_path.is_file() else ''
    if got != want:
        print(f'{fixture_path} drifted from {expected_dir}; rerun store_freeze_corpus.py freeze', file=sys.stderr)
        return 1
    print(f'corpus format-{fmt} ok ({len(dir_files)} dir files, {len(bucket_objects)} bucket objects)')
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    p_freeze = sub.add_parser('freeze')
    p_freeze.add_argument('--root', type=Path, default=ROOT)
    p_freeze.add_argument('--compiler', type=Path, required=True)
    p_freeze.add_argument('--runtime', type=Path, required=True)
    p_freeze.add_argument('--cc', type=Path)
    p_freeze.add_argument('--backend', choices=['cranelift', 'llvm'], default='cranelift')
    p_check = sub.add_parser('check')
    p_check.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    return freeze(args) if args.command == 'freeze' else check(args)


if __name__ == '__main__':
    raise SystemExit(main())
