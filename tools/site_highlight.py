#!/usr/bin/env python3
"""Colour the site's In code snippets and README hero SVGs with the editor grammar.

Reads `const CODE` in site/index.html, parses the Hirsel lines of each snippet (the lines before
its first `$ ` transcript line) with editors/tree-sitter-hirsel, runs queries/highlights.scm, and
writes the token ranges as `const CODE_HL` between the markers below, so the page ships plain
ranges and no parser. Also renders docs/assets/readme-hero-{dark,light}.svg from README.md's hero
Hirsel snippet. Where captures overlap on one node the earliest pattern in the query wins, as in
the Tree-sitter highlighter. Snippets are never rewritten; one that does not parse is reported and
nothing is written.

Usage: tools/site_highlight.py [--check]
Needs a C compiler and py-tree-sitter 0.25.2; it re-runs itself under the interpreter that
editors/tree-sitter-hirsel/check-local installs when tree_sitter is not importable.
"""

import json
import re
import sys
import tempfile
from pathlib import Path

from render_code_svg import ensure_binding, load_grammar, sync_readme_svgs, tokenize_lines

ROOT = Path(__file__).resolve().parents[1]
HTML = ROOT / "site" / "index.html"
BEGIN = "/* CODE_HL: generated by tools/site_highlight.py from editors/tree-sitter-hirsel; do not edit */\n"
END = "/* end CODE_HL */\n"

# capture -> class. k keyword, d defined name, t type, v literal, o operator and punctuation,
# c comment; captures not listed (calls, parameters, properties) stay in plain ink.
CLASS = {
    "keyword": "k", "keyword.conditional": "k", "keyword.repeat": "k", "keyword.return": "k",
    "function": "d", "type.definition": "d",
    "type": "t", "type.builtin": "t", "constructor": "t", "attribute": "t",
    "string": "v", "character": "v", "number": "v", "number.float": "v", "boolean": "v",
    "operator": "o", "punctuation.bracket": "o", "punctuation.delimiter": "o",
    "comment": "c",
}


def snippets(html):
    block = html[html.index("const CODE = {"):]
    block = block[:block.index("\n};\n")]
    out = {}
    for m in re.finditer(r"\n  (\w+): \{ no: \[[\d, ]*\], src: \[(.*?')\] \}", block, re.S):
        lines = [json.loads('"' + s.replace("\\'", "'").replace('"', '\\"') + '"')
                 for s in re.findall(r"'((?:[^'\\]|\\.)*)'", m[2])]
        out[m[1]] = lines
    return out


def highlight(html, parser, query):
    result, errors = {}, []
    for name, lines in snippets(html).items():
        code = []
        for line in lines:
            if line.startswith("$ "):
                break
            code.append(line)
        if not code:
            continue
        try:
            result[name] = tokenize_lines(parser, query, code, CLASS, label=name)
        except ValueError as error:
            errors.append(str(error))
    if errors:
        sys.exit("site_highlight:\n" + "\n".join(errors))
    body = "const CODE_HL = {\n" + "".join(
        f"  {name}: [\n" + "".join("    " + json.dumps(r, separators=(",", ":")).replace('"', "'") + ",\n" for r in rows) + "  ],\n"
        for name, rows in result.items()) + "};\n"
    return BEGIN + body + END


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit("usage: site_highlight.py [--check]")
    ensure_binding(__file__)
    html = HTML.read_text(encoding="utf-8")
    if html.count(BEGIN) != 1 or html.count(END) != 1:
        sys.exit("site_highlight: site/index.html needs one CODE_HL marker pair")
    with tempfile.TemporaryDirectory(prefix="site-highlight-") as temp:
        _grammar, parser, query = load_grammar(temp)
        block = highlight(html, parser, query)
        try:
            stale_svgs = sync_readme_svgs(parser, query, check=check)
        except ValueError as error:
            sys.exit(f"site_highlight:\n{error}")
    a, b = html.index(BEGIN), html.index(END) + len(END)
    new = html[:a] + block + html[b:]
    if check:
        stale = []
        if new != html:
            stale.append("site/index.html")
        stale.extend(str(p.relative_to(ROOT)) for p in stale_svgs)
        if stale:
            sys.exit(f"site_highlight: stale generated output ({', '.join(stale)}); run tools/site_highlight.py")
        return
    if new != html:
        HTML.write_text(new, encoding="utf-8")


if __name__ == "__main__":
    main()
