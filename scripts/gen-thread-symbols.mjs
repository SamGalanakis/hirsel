#!/usr/bin/env node
// Regenerates the Thread symbol vocabulary artwork from Lucide (ISC).
//
//   node scripts/gen-thread-symbols.mjs --lucide <path to lucide-solid package>
//
// It writes the web artwork table (app/src/threads/thread-symbol-art.ts) and
// the Android vector drawables (android/app/src/main/res/drawable/ic_symbol_*.xml)
// from one source, so both clients draw the same glyph. The vocabulary itself
// — the names and their order — lives in crates/hirsel-proto/src/thread_icon.rs
// and is mirrored here; a name whose Lucide source is spelled differently maps
// through SOURCE below.
import { mkdirSync, readFileSync, readdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lucideArgument = process.argv.indexOf("--lucide");
if (lucideArgument < 0) {
  console.error("usage: node scripts/gen-thread-symbols.mjs --lucide <lucide-solid package dir>");
  process.exit(2);
}
const icons = join(process.argv[lucideArgument + 1], "dist/esm/icons");

// Lucide spellings for vocabulary names that read better in the picker.
const SOURCE = { home: "house", flask: "flask-conical" };

const names = readFileSync(join(root, "crates/hirsel-proto/src/thread_icon.rs"), "utf8")
  .match(/pub const THREAD_SYMBOLS: \[&str; \d+\] = \[([\s\S]*?)\];/)[1]
  .match(/"([a-z-]+)"/g)
  .map(quoted => quoted.slice(1, -1));

function nodes(name) {
  const file = join(icons, `${SOURCE[name] ?? name}.mjs`);
  const literal = readFileSync(file, "utf8").match(/const iconNode = (\[[\s\S]*?\]);\n/)[1];
  // The module body is a plain array literal of [tag, attributes] pairs.
  return new Function(`return ${literal};`)().map(([tag, attrs]) => {
    const kept = { ...attrs };
    delete kept.key;
    return [tag, kept];
  });
}

const round = value => String(Math.round(Number(value) * 1000) / 1000);

/** One Android `pathData` string per node: Android draws paths only. */
function pathData([tag, a]) {
  if (tag === "path") return a.d;
  if (tag === "line") return `M${round(a.x1)} ${round(a.y1)}L${round(a.x2)} ${round(a.y2)}`;
  if (tag === "polyline" || tag === "polygon") {
    const points = a.points.trim().split(/[\s,]+/).map(round);
    let data = `M${points[0]} ${points[1]}`;
    for (let index = 2; index < points.length; index += 2) data += `L${points[index]} ${points[index + 1]}`;
    return tag === "polygon" ? `${data}Z` : data;
  }
  if (tag === "circle") {
    const [cx, cy, r] = [Number(a.cx), Number(a.cy), Number(a.r)];
    return `M${round(cx - r)} ${round(cy)}a${round(r)} ${round(r)} 0 1 0 ${round(2 * r)} 0a${round(r)} ${round(r)} 0 1 0 ${round(-2 * r)} 0Z`;
  }
  if (tag === "rect") {
    const [x, y, w, h] = [Number(a.x), Number(a.y), Number(a.width), Number(a.height)];
    const r = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2, h / 2);
    if (!r) return `M${round(x)} ${round(y)}h${round(w)}v${round(h)}h${round(-w)}Z`;
    return `M${round(x + r)} ${round(y)}h${round(w - 2 * r)}a${round(r)} ${round(r)} 0 0 1 ${round(r)} ${round(r)}`
      + `v${round(h - 2 * r)}a${round(r)} ${round(r)} 0 0 1 ${round(-r)} ${round(r)}`
      + `h${round(-(w - 2 * r))}a${round(r)} ${round(r)} 0 0 1 ${round(-r)} ${round(-r)}`
      + `v${round(-(h - 2 * r))}a${round(r)} ${round(r)} 0 0 1 ${round(r)} ${round(-r)}Z`;
  }
  throw new Error(`unsupported Lucide node: ${tag}`);
}

const art = names.map(name => [name, nodes(name)]);

const web = `// GENERATED by scripts/gen-thread-symbols.mjs — do not edit by hand.
// Lucide SVG artwork, ISC license. See app/src/components/ui/lucide-LICENSE.txt.
import type { ThreadSymbol } from "./thread-symbols";

/** One \`d\` attribute per stroked path, in draw order. */
export const THREAD_SYMBOL_ART: Record<ThreadSymbol, string[]> = {
${art.map(([name, node]) => `  "${name}": [${node.map(one => JSON.stringify(pathData(one))).join(", ")}],`).join("\n")}
};
`;
writeFileSync(join(root, "app/src/threads/thread-symbol-art.ts"), web);

const drawables = join(root, "android/app/src/main/res/drawable");
mkdirSync(drawables, { recursive: true });
for (const file of readdirSync(drawables)) {
  if (file.startsWith("ic_symbol_")) rmSync(join(drawables, file));
}
for (const [name, node] of art) {
  const paths = node.map(one => `    <path
        android:pathData="${pathData(one).replace(/&/g, "&amp;").replace(/"/g, "&quot;")}"
        android:strokeColor="#FF000000"
        android:strokeWidth="2"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />`).join("\n");
  writeFileSync(join(drawables, `ic_symbol_${name.replace(/-/g, "_")}.xml`), `<!-- GENERATED by scripts/gen-thread-symbols.mjs. Lucide artwork, ISC license. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths}
</vector>
`);
}

const kotlin = `// GENERATED by scripts/gen-thread-symbols.mjs — do not edit by hand.
package dev.hirsel.android.chat

import dev.hirsel.android.R

/** Vocabulary symbol name to its generated vector drawable. */
internal val THREAD_SYMBOL_DRAWABLES: Map<String, Int> = mapOf(
${art.map(([name]) => `    "${name}" to R.drawable.ic_symbol_${name.replace(/-/g, "_")},`).join("\n")}
)
`;
writeFileSync(join(root, "android/app/src/main/kotlin/dev/hirsel/android/chat/ThreadSymbolArt.kt"), kotlin);

console.log(`wrote ${art.length} symbols to app/src/threads/thread-symbol-art.ts and ${drawables}, plus the Kotlin drawable map`);
