pub(super) fn number(definition: &DefPath) -> Option<u32> {
    let [module] = definition.0.modules.as_slice() else {
        return None;
    };
    if !definition.package_is("core", "1") {
        return None;
    }
    let key = (module.as_str(), definition.0.name.as_str());
    let row = BUILTIN_SEMANTICS
        .binary_search_by_key(&key, |&(module, name, _)| (module, name))
        .ok()?;
    Some(BUILTIN_SEMANTICS[row].2)
}
