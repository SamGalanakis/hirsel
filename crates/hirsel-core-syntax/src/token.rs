#[derive(serde::Serialize, serde::Deserialize, Clone, Copy, Debug, Eq, PartialEq)]
pub enum TriviaKind {
    Space,
    Newline,
    LineComment,
    BlockComment,
    DocLine,
    DocBlock,
}
#[derive(serde::Serialize, serde::Deserialize, Clone, Copy, Debug, Eq, PartialEq)]
pub enum TokenKind {
    Ident,
    Label,
    Keyword(Keyword),
    Punct(Punct),
    Integer,
    Float,
    Character,
    Byte,
    String,
    Bytes,
    Trivia(TriviaKind),
    Invalid,
    Eof,
}
#[derive(serde::Serialize, serde::Deserialize, Clone, Debug, Eq, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}
