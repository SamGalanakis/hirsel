#!/usr/bin/env python3
"""Generate the std Unicode tables from the four UCD files pinned in UNI-1."""

import argparse
from bisect import bisect_right
from hashlib import sha256
from pathlib import Path


STD = Path(__file__).resolve().parents[1] / "std"
BEGIN = "// BEGIN generated by core/tools/unicode_tables.py\n"
END = "// END\n"
NOTICE = "// Unicode data is licensed under Unicode-3.0 (https://www.unicode.org/license.txt)."
DIGESTS = {
    "UnicodeData.txt": "0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950",
    "SpecialCasing.txt": "8538dea57c184f1ef3783885ea79677b10f6efa06423717157e63712f14d1ad2",
    "DerivedCoreProperties.txt": "09c928886a178fcafd93c29e4bd59073a058e5a100b716d425cb563ab50f68c9",
    "PropList.txt": "f438f532e8737bb8a2702126cdf9c4af5e357c58c7acf9d9eb2fc7c1a1d955d6",
}
CATEGORIES = "Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs Zl Zp Cc Cf Co Cn".split()
PROPERTIES = ("Other_Alphabetic", "Other_Lowercase", "Other_Uppercase", "White_Space")
LIMIT = 0x110000


def scalars():
    yield from range(0xD800)
    yield from range(0xE000, LIMIT)


def read_ucd(directory):
    files = {}
    for name, expected in DIGESTS.items():
        data = (directory / name).read_bytes()
        actual = sha256(data).hexdigest()
        if actual != expected:
            raise ValueError(f"{name}: SHA-256 {actual}, expected {expected} (UNI-1)")
        files[name] = data.decode("utf-8")
    return files


def records(source):
    for line in source.splitlines():
        content = line.partition("#")[0].strip()
        if content:
            yield [field.strip() for field in content.split(";")]


def unicode_data(files):
    tags = {name: index for index, name in enumerate(CATEGORIES)}
    categories = bytearray([tags["Cn"]]) * LIMIT
    upper, lower = {}, {}
    start = None
    for entry in records(files["UnicodeData.txt"]):
        code = int(entry[0], 16)
        name, category = entry[1:3]
        if name.endswith(", First>"):
            start = code
            continue
        if category != "Cs":
            first = start if name.endswith(", Last>") else code
            categories[first:code + 1] = bytes([tags[category]]) * (code - first + 1)
        start = None
        for field, mappings in ((12, upper), (13, lower)):
            if entry[field]:
                mappings[code] = (int(entry[field], 16),)
    for code, low, _, up, condition, *_ in records(files["SpecialCasing.txt"]):
        if not condition:
            upper[int(code, 16)] = tuple(int(value, 16) for value in up.split())
            lower[int(code, 16)] = tuple(int(value, 16) for value in low.split())
    return categories, upper, lower


def properties(source, names):
    result = {name: set() for name in names}
    for field, name, *_ in records(source):
        if name in result:
            first, _, last = field.partition("..")
            result[name].update(range(int(first, 16), int(last or first, 16) + 1))
    return result


def verify_properties(categories, props, derived):
    expected = (
        ("Alphabetic", "Other_Alphabetic", "Lu Ll Lt Lm Lo Nl"),
        ("Lowercase", "Other_Lowercase", "Ll"),
        ("Uppercase", "Other_Uppercase", "Lu"),
    )
    for name, other, groups in expected:
        tags = {CATEGORIES.index(group) for group in groups.split()}
        actual = {code for code in scalars() if categories[code] in tags} | props[other]
        mismatch = actual ^ derived[name]
        if mismatch:
            raise ValueError(f"{name}: PropList and DerivedCoreProperties disagree at U+{min(mismatch):04X}")


def category_runs(categories):
    result = []
    previous = None
    for code in scalars():
        tag = categories[code]
        if tag != previous:
            result.append((code << 5) | tag)
            previous = tag
    return result


def ranges(points):
    result = []
    for code in sorted(points):
        if result and result[-1][1] + 1 == code:
            result[-1] = (result[-1][0], code)
        else:
            result.append((code, code))
    return result


def case_tables(mappings, expansions):
    runs = []
    multi = []
    for code, mapped in sorted(mappings.items()):
        if mapped == (code,):
            continue
        if len(mapped) > 1:
            text = "".join(chr(value) for value in mapped).encode("utf-8")
            multi.append((code, (len(expansions) << 4) | len(text)))
            expansions.extend(text)
            continue
        delta = mapped[0] - code
        if runs:
            start, length, stride, previous = runs[-1]
            gap = code - (start + (length - 1) * stride)
            if delta == previous and (gap == stride or length == 1 and gap == 2):
                runs[-1] = (start, length + 1, gap, delta)
                continue
        runs.append((code, 1, 1, delta))
    # 21 bits for a scalar start, 10 for the run length, one for the stride.
    if any(length >= 1024 for _, length, _, _ in runs):
        raise ValueError("case run too long for table encoding")
    return [((start << 11) | (length << 1) | (stride - 1), delta) for start, length, stride, delta in runs], multi


def inline(name, element, values):
    rows = "".join(f"    {value},\n" for value in values)
    return f"const {name}: Inline[{element}, {len(values)}] =[\n{rows}]"


def indexed_tables(name, element, tables):
    values = []
    lines = []
    for key, rows in tables:
        lines.append(f"const {key}_LO: u64 = {len(values)}")
        values.extend(rows)
        lines.append(f"const {key}_HI: u64 = {len(values)}")
    lines.append(inline(name, element, values))
    return lines


def verify_categories(categories, runs, props, property_ranges):
    starts = [word >> 5 for word in runs]
    decoded = {
        name: {code for lo, hi in entries for code in range(lo, hi + 1)}
        for name, entries in property_ranges
    }
    if decoded != props:
        raise ValueError("encoded property ranges differ from PropList")
    for code in scalars():
        if runs[bisect_right(starts, code) - 1] & 31 != categories[code]:
            raise ValueError(f"encoded category differs from UnicodeData at U+{code:04X}")


def verify_case(mappings, runs, multi, expansions):
    starts = [word >> 11 for word, _ in runs]
    expansions_by_code = {}
    for code, packed in multi:
        start, length = packed >> 4, packed & 15
        expansions_by_code[code] = tuple(map(ord, expansions[start:start + length].decode("utf-8")))
    for code in scalars():
        result = expansions_by_code.get(code)
        if result is None:
            target = code
            index = bisect_right(starts, code) - 1
            if index >= 0:
                word, delta = runs[index]
                offset = code - starts[index]
                length = (word >> 1) & 1023
                stride = 1 + (word & 1)
                if offset % stride == 0 and offset // stride < length:
                    target += delta
            result = (target,)
        if result != mappings.get(code, (code,)):
            raise ValueError(f"encoded case map differs from UCD at U+{code:04X}")


def generate(files, check):
    categories, upper, lower = unicode_data(files)
    props = properties(files["PropList.txt"], PROPERTIES)
    derived = properties(files["DerivedCoreProperties.txt"], ("Alphabetic", "Lowercase", "Uppercase"))
    verify_properties(categories, props, derived)
    runs = category_runs(categories)
    property_ranges = [(name, ranges(points)) for name, points in props.items()]
    expansions = bytearray()
    upper_runs, upper_multi = case_tables(upper, expansions)
    lower_runs, lower_multi = case_tables(lower, expansions)
    if check:
        verify_categories(categories, runs, props, property_ranges)
        verify_case(upper, upper_runs, upper_multi, expansions)
        verify_case(lower, lower_runs, lower_multi, expansions)
    char_lines = [
        NOTICE,
        f"const CATEGORY_COUNT: u64 = {len(runs)}",
        inline("CATEGORY_RUNS", "u32", runs),
        *indexed_tables("PROPERTY_RANGES", "(u32, u32)", [
            (name.upper(), entries) for name, entries in property_ranges
        ]),
    ]
    expansion_text = "".join(f"\\u{{{ord(value):x}}}" for value in expansions.decode("utf-8"))
    string_lines = [
        NOTICE,
        *indexed_tables("CASE_RUNS", "(u32, i32)", [
            ("UPPER_RUN", upper_runs), ("LOWER_RUN", lower_runs)
        ]),
        *indexed_tables("CASE_MULTI", "(u32, u32)", [
            ("UPPER_MULTI", upper_multi), ("LOWER_MULTI", lower_multi)
        ]),
        f'const CASE_EXPANSIONS: String = "{expansion_text}"',
    ]
    for lines in (char_lines, string_lines):
        notice, *declarations = lines
        yield notice + "\n" + "\n\n".join(declarations) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ucd", type=Path, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        for name, tables in zip(("char", "string"), generate(read_ucd(args.ucd), args.check)):
            path = STD / f"{name}.hirsel"
            old = path.read_text(encoding="utf-8")
            head, begin, tail = old.partition(BEGIN)
            _, end, rest = tail.partition(END)
            if not begin or not end or BEGIN in rest:
                raise ValueError(f"{path}: expected one generated region")
            new = head + begin + tables + end + rest
            if args.write:
                path.write_text(new, encoding="utf-8")
            elif old != new:
                raise ValueError(f"{path}: generated tables differ")
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    if args.check:
        print("Unicode 18.0.0 categories, properties and case maps agree with UCD across 1,112,064 scalars.")


if __name__ == "__main__":
    main()
