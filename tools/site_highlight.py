#!/usr/bin/env python3
"""Colour the site's In code snippets with the editor grammar.

Reads `const CODE` in site/index.html, parses the Hirsel lines of each snippet (the lines before
its first `$ ` transcript line) with editors/tree-sitter-hirsel, runs queries/highlights.scm, and
writes the token ranges as `const CODE_HL` between the markers below, so the page ships plain
ranges and no parser. Where captures overlap on one node the earliest pattern in the query wins,
as in the Tree-sitter highlighter. Snippets are never rewritten; one that does not parse is
reported and nothing is written.

Usage: tools/site_highlight.py [--check]
Needs a C compiler and py-tree-sitter 0.25.2; it re-runs itself under the interpreter that
editors/tree-sitter-hirsel/check-local installs when tree_sitter is not importable.
"""

import ctypes
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GRAMMAR = ROOT / "editors" / "tree-sitter-hirsel"
HTML = ROOT / "site" / "index.html"
BEGIN = "/* CODE_HL: generated by tools/site_highlight.py from editors/tree-sitter-hirsel; do not edit */\n"
END = "/* end CODE_HL */\n"

# capture -> class. k keyword, d defined name, t type, v literal, o operator and punctuation,
# c comment; captures not listed (calls, parameters, properties) stay in plain ink.
CLASS = {
    "keyword": "k", "keyword.conditional": "k", "keyword.repeat": "k", "keyword.return": "k",
    "function": "d", "type.definition": "d",
    "type": "t", "type.builtin": "t", "constructor": "t", "attribute": "t",
    "string": "v", "character": "v", "number": "v", "number.float": "v", "boolean": "v",
    "operator": "o", "punctuation.bracket": "o", "punctuation.delimiter": "o",
    "comment": "c",
}


def ensure_binding():
    try:
        import tree_sitter  # noqa: F401
    except ImportError:
        python = (Path.home() / ".cache" / "hirsel-tree-sitter"
                  / f"binding-0.25.2-{sys.implementation.cache_tag}" / "bin" / "python")
        if not python.is_file() or os.environ.get("SITE_HIGHLIGHT_REEXEC"):
            sys.exit("site_highlight: py-tree-sitter 0.25.2 missing; run editors/tree-sitter-hirsel/check-local once")
        os.execve(python, [str(python), __file__, *sys.argv[1:]], dict(os.environ, SITE_HIGHLIGHT_REEXEC="1"))


def snippets(html):
    block = html[html.index("const CODE = {"):]
    block = block[:block.index("\n};\n")]
    out = {}
    for m in re.finditer(r"\n  (\w+): \{ no: \[[\d, ]*\], src: \[(.*?')\] \}", block, re.S):
        lines = [json.loads('"' + s.replace("\\'", "'").replace('"', '\\"') + '"')
                 for s in re.findall(r"'((?:[^'\\]|\\.)*)'", m[2])]
        out[m[1]] = lines
    return out


def highlight(html, temp):
    from tree_sitter import Language, Parser, Query, QueryCursor
    lib = Path(temp) / "hirsel.so"
    subprocess.run(["cc", "-shared", "-fPIC", "-O1", "-I", str(GRAMMAR / "src"),
                    str(GRAMMAR / "src" / "parser.c"), str(GRAMMAR / "src" / "scanner.c"),
                    "-o", str(lib)], check=True)
    grammar = ctypes.CDLL(str(lib))
    entry = grammar.tree_sitter_hirsel
    entry.restype = ctypes.c_void_p
    capsule = ctypes.pythonapi.PyCapsule_New
    capsule.argtypes = (ctypes.c_void_p, ctypes.c_char_p, ctypes.c_void_p)
    capsule.restype = ctypes.py_object
    language = Language(capsule(entry(), b"tree_sitter.Language", None))
    parser = Parser(language)
    query = Query(language, (GRAMMAR / "queries" / "highlights.scm").read_text())
    result, errors = {}, []
    for name, lines in snippets(html).items():
        code = []
        for line in lines:
            if line.startswith("$ "):
                break
            if not line.isascii():
                errors.append(f"{name}: non-ASCII line {line!r}")
            code.append(line)
        if not code:
            continue
        source = "\n".join(code).encode()
        tree = parser.parse(source)
        if tree.root_node.has_error:
            errors.append(f"{name}: parse error\n{tree.root_node}")
            continue
        # one class per node: the first pattern that captures it, as the highlighter picks
        chosen = {}
        for pattern, caps in QueryCursor(query).matches(tree.root_node):
            for capture, nodes in caps.items():
                for node in nodes:
                    key = (node.start_byte, node.end_byte)
                    if key not in chosen or pattern < chosen[key][0]:
                        chosen[key] = (pattern, capture)
        starts = [0]
        for line in code:
            starts.append(starts[-1] + len(line) + 1)
        ranges = [[] for _ in code]
        for (a, b), (_, capture) in sorted(chosen.items()):
            cls = CLASS.get(capture)
            if not cls:
                continue
            row = max(i for i, s in enumerate(starts) if s <= a)
            if b > starts[row] + len(code[row]):
                errors.append(f"{name}: capture {capture} spans lines")
                continue
            ranges[row].append([a - starts[row], b - a, cls])
        for row in ranges:
            for prev, cur in zip(row, row[1:]):
                if cur[0] < prev[0] + prev[1]:
                    errors.append(f"{name}: overlapping ranges {prev} {cur}")
        result[name] = ranges
    if errors:
        sys.exit("site_highlight:\n" + "\n".join(errors))
    body = "const CODE_HL = {\n" + "".join(
        f"  {name}: [\n" + "".join("    " + json.dumps(r, separators=(",", ":")).replace('"', "'") + ",\n" for r in rows) + "  ],\n"
        for name, rows in result.items()) + "};\n"
    return BEGIN + body + END


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit("usage: site_highlight.py [--check]")
    ensure_binding()
    html = HTML.read_text(encoding="utf-8")
    if html.count(BEGIN) != 1 or html.count(END) != 1:
        sys.exit("site_highlight: site/index.html needs one CODE_HL marker pair")
    with tempfile.TemporaryDirectory(prefix="site-highlight-") as temp:
        block = highlight(html, temp)
    a, b = html.index(BEGIN), html.index(END) + len(END)
    new = html[:a] + block + html[b:]
    if check:
        if new != html:
            sys.exit("site_highlight: site/index.html is stale; run tools/site_highlight.py")
        return
    if new != html:
        HTML.write_text(new, encoding="utf-8")


if __name__ == "__main__":
    main()
