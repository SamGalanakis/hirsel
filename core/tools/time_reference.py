#!/usr/bin/env python3
"""Print the CPython datetime oracle for the std.time day and weekday laws."""

from datetime import date


T1_DATES = (
    (1, 1, 1),
    (99, 12, 31), (100, 1, 1), (100, 2, 28), (100, 3, 1),
    (399, 12, 31), (400, 1, 1), (400, 2, 29), (400, 3, 1), (401, 1, 1),
    (799, 12, 31), (800, 1, 1), (800, 2, 29),
    (1199, 12, 31), (1200, 1, 1), (1200, 2, 29),
    (1582, 10, 4), (1582, 10, 15),
    (1599, 12, 31), (1600, 1, 1), (1600, 2, 29),
    (1699, 12, 31), (1700, 3, 1), (1799, 12, 31), (1800, 3, 1),
    (1899, 12, 31), (1900, 2, 28), (1900, 3, 1),
    (1969, 12, 31), (1970, 1, 1),
    (1999, 12, 31), (2000, 1, 1), (2000, 2, 29), (2000, 3, 1),
    (2024, 2, 29), (2100, 3, 1),
    (2399, 12, 31), (2400, 1, 1), (9999, 12, 31),
)
T2_DATES = ((1969, 12, 28), (1970, 1, 1), (2000, 1, 1), (9999, 12, 31))


def main():
    for law, dates in (('T1', T1_DATES), ('T2', T2_DATES)):
        print(law)
        for year, month, day in dates:
            value = date(year, month, day)
            print(f'{year:04}-{month:02}-{day:02} {value.toordinal() - 719163} {value.weekday()}')


if __name__ == '__main__':
    main()
