macro_rules! table {
    ($($symbol:ident $class:ident,)*) => {
        /// Every runtime symbol loaded code may import, sorted by symbol.
        pub const ROWS: &[(&str, $crate::Class)] =
            &[$((stringify!($symbol), $crate::Class::$class)),*];
    };
}
