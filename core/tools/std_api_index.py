#!/usr/bin/env python3
"""Render core/std/API-INDEX.md from `hirsel inspect --interface --json`.

Set HIRSEL to select the compiler executable. Module contracts live in api/<module>.md.
--write owns the whole output;
--check compares every byte, including its tail.
"""

import json
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
STD = ROOT / "core" / "std"
API = STD / "API-INDEX.md"
HEADER = "| Module | Extends | Ops | Operations |"


def table() -> str:
    interface = json.loads(subprocess.check_output([
        os.environ.get("HIRSEL", "hirsel"), "inspect", "--std", "--interface",
        "--json", "--libraries", str(ROOT / "core"),
    ]))
    if interface["version"] != 1:
        raise ValueError("unsupported Hirsel interface version")
    rows = ["# Standard library operation index", "",
            "Generated by `core/tools/std_api_index.py --write`. Do not edit.", "",
            "[API overview](API.md). Module names link to their contracts.", "",
            HEADER, "|---|---|---|---|"]
    extends = total = 0
    modules = set()
    for module in interface["modules"]:
        name = "/".join(module["path"])
        modules.add(name)
        ops = [item["name"] for item in module["items"] if item["kind"] == "function"]
        ext = module["extends_core"]
        extends += ext
        total += len(ops)
        contract = f"api/{name}.md"
        if not (STD / contract).is_file():
            raise ValueError(f"core/std/{name}.hirsel: missing module contract core/std/{contract}")
        rows.append(f"| [{name}]({contract}) | {'yes' if ext else ''} | {len(ops)} | {', '.join(ops)} |")
    rows.append(f"| **total** | **{extends} of {len(modules)}** | **{total}** | |")
    shared = [path for path in sorted((STD / "api").glob("*.md"))
              if path.stem not in modules]
    if shared:
        rows.extend(["", "## Related module contracts", ""])
        rows.extend(f"- [{path.stem}](api/{path.name})" for path in shared)
    return "\n".join(rows) + "\n"


def main() -> int:
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    try:
        want = table()
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        sys.stderr.write(str(error) + "\n")
        return 1
    if mode == "--write":
        API.write_text(want)
        return 0
    if mode == "--check":
        if not API.is_file() or API.read_bytes() != want.encode():
            sys.stderr.write("core/std/API-INDEX.md: operation index is stale; run core/tools/std_api_index.py --write\n")
            return 1
        return 0
    sys.stdout.write(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())
