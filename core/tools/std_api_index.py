#!/usr/bin/env python3
"""The complete generated core/std/API-INDEX.md, from core/std/*.hirsel.

A module extends core when core/core has a file of the same name (LANG-7).
An operation is a top-level `pub fn`. Module contracts live in api/<module>.md.
--write owns the whole output; --check compares every byte, including its tail.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
STD = ROOT / "core" / "std"
CORE = ROOT / "core" / "core"
API = STD / "API-INDEX.md"
HEADER = "| Module | Extends | Ops | Operations |"
PUB_FN = re.compile(r"^pub fn ([a-z_][a-z0-9_]*)", re.M)


def table() -> str:
    core = {p.stem for p in CORE.glob("*.hirsel")}
    rows = ["# Standard library operation index", "",
            "Generated by `core/tools/std_api_index.py --write`. Do not edit.", "",
            "[API overview](API.md). Module names link to their contracts.", "",
            HEADER, "|---|---|---|---|"]
    extends = total = modules = 0
    for path in sorted(STD.glob("*.hirsel")):
        ops = PUB_FN.findall(path.read_text())
        ext = path.stem in core
        extends += ext
        modules += 1
        total += len(ops)
        contract = f"api/{path.stem}.md"
        if not (STD / contract).is_file():
            raise ValueError(f"{path.relative_to(ROOT)}: missing module contract core/std/{contract}")
        rows.append(f"| [{path.stem}]({contract}) | {'yes' if ext else ''} | {len(ops)} | {', '.join(ops)} |")
    rows.append(f"| **total** | **{extends} of {modules}** | **{total}** | |")
    shared = [path for path in sorted((STD / "api").glob("*.md"))
              if not (STD / (path.stem + ".hirsel")).is_file()]
    if shared:
        rows.extend(["", "## Related module contracts", ""])
        rows.extend(f"- [{path.stem}](api/{path.name})" for path in shared)
    return "\n".join(rows) + "\n"


def main() -> int:
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    try:
        want = table()
    except ValueError as error:
        sys.stderr.write(str(error) + "\n")
        return 1
    if mode == "--write":
        API.write_text(want)
        return 0
    if mode == "--check":
        if not API.is_file() or API.read_bytes() != want.encode():
            sys.stderr.write("core/std/API-INDEX.md: operation index is stale; run core/tools/std_api_index.py --write\n")
            return 1
        return 0
    sys.stdout.write(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())
