def starlark(value, indent: int = 4) -> str:
    """Render a JSON-like value in the layout buildifier uses for BUCK files."""
    pad = " " * indent
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, Raw):
        return value.text
    if isinstance(value, list):
        if not value:
            return "[]"
        if all(isinstance(v, (str, Raw)) for v in value) and len(value) == 1:
            return f"[{starlark(value[0])}]"
        inner = "".join(f"{pad}    {starlark(v, indent + 4)},\n" for v in value)
        return f"[\n{inner}{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        inner = "".join(f"{pad}    {json.dumps(k)}: {starlark(v, indent + 4)},\n" for k, v in value.items())
        return f"{{\n{inner}{pad}}}"
    if isinstance(value, int) and not isinstance(value, bool):
        return str(value)
    raise TypeError(value)


class Raw:
    def __init__(self, text: str):
        self.text = text


def call(rule: str, **attrs) -> str:
    body = "".join(f"    {key} = {starlark(value)},\n" for key, value in attrs.items() if value is not None)
    return f"{rule}(\n{body})\n"


