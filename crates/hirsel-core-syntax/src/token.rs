#[derive(serde::Serialize, serde::Deserialize, Clone, Copy, Debug, Eq, PartialEq, Hash)]
pub enum Keyword {
    Fn,
    Let,
    Mut,
    Match,
    If,
    Else,
    Loop,
    While,
    For,
    In,
    Break,
    Continue,
    Return,
    Take,
    Copy,
    View,
    Type,
    Stable,
    Resource,
    Scoped,
    Region,
    Bound,
    Pub,
    Opaque,
    Const,
    Where,
    True,
    False,
}
impl Keyword {
    pub fn from_spelling(s: &str) -> Option<Self> {
        Some(match s {
            "fn" => Self::Fn,
            "let" => Self::Let,
            "mut" => Self::Mut,
            "match" => Self::Match,
            "if" => Self::If,
            "else" => Self::Else,
            "loop" => Self::Loop,
            "while" => Self::While,
            "for" => Self::For,
            "in" => Self::In,
            "break" => Self::Break,
            "continue" => Self::Continue,
            "return" => Self::Return,
            "take" => Self::Take,
            "copy" => Self::Copy,
            "view" => Self::View,
            "type" => Self::Type,
            "stable" => Self::Stable,
            "resource" => Self::Resource,
            "scoped" => Self::Scoped,
            "region" => Self::Region,
            "bound" => Self::Bound,
            "pub" => Self::Pub,
            "opaque" => Self::Opaque,
            "const" => Self::Const,
            "where" => Self::Where,
            "true" => Self::True,
            "false" => Self::False,
            _ => return None,
        })
    }
    pub fn spelling(self) -> &'static str {
        match self {
            Self::Fn => "fn",
            Self::Let => "let",
            Self::Mut => "mut",
            Self::Match => "match",
            Self::If => "if",
            Self::Else => "else",
            Self::Loop => "loop",
            Self::While => "while",
            Self::For => "for",
            Self::In => "in",
            Self::Break => "break",
            Self::Continue => "continue",
            Self::Return => "return",
            Self::Take => "take",
            Self::Copy => "copy",
            Self::View => "view",
            Self::Type => "type",
            Self::Stable => "stable",
            Self::Resource => "resource",
            Self::Scoped => "scoped",
            Self::Region => "region",
            Self::Bound => "bound",
            Self::Pub => "pub",
            Self::Opaque => "opaque",
            Self::Const => "const",
            Self::Where => "where",
            Self::True => "true",
            Self::False => "false",
        }
    }
}
