def execution_sizes() -> str:
    """Measured requests stay separate from crate BUCK files."""
    data = json.loads(READS.text(HERE / "action-sizes.json"))
    profiles = data["profiles"]
    special = data.get("special_requests", {})
    budgets = {(1, 1048576, "")} | {(r["cpu_count"], r["memory_kb"], "fast" if name == "precheck" else "") for name, r in special.items()}
    requests = {}
    for profile in ("dev", "release"):
        requests[profile] = {}
        for target, row in sorted(profiles[profile].items()):
            cpu, memory = row["cpu_count"], row["memory_kb"]
            ceiling = 8 if target in CALIBRATED_CPUS[profile] else MAX_CPUS
            if type(cpu) is not int or not 1 <= cpu <= ceiling or type(memory) is not int or not 0 < memory <= 8388608:
                raise ValueError(f"invalid execution request: {profile}/{target}")
            if cpu != compile_cpus(profile, target, row.get("mean_cores", row["p95_cores"])):
                raise ValueError(f"stale CPU sizing: {profile}/{target}; regenerate action-sizes.json")
            budgets.add((cpu, memory, CPU_CLASSES[profile].get(target, "")))
            requests[profile][target] = [cpu, memory]
        for target, cpu_class in CPU_CLASSES[profile].items():
            cpu, memory = requests[profile].get(target, [1, 1048576])
            budgets.add((cpu, memory, cpu_class))
    # A profile with no fresh execution inherits the measured sibling's
    # request in platforms.bzl. Register its CPU class combination too.
    for profile in ("dev", "release"):
        other = "release" if profile == "dev" else "dev"
        for target in requests[other].keys() - requests[profile].keys():
            memory = requests[other][target][1]
            budgets.add((1, memory, CPU_CLASSES[profile].get(target, "")))
    return (HEADER + "# Requests derived from action-sizes.json; evidence and sizing policy in README.md.\n"
            + "POOL_BUDGETS = " + starlark([list(b) for b in sorted(budgets)]) + "\n\n"
            + "SPECIAL_REQUESTS = " + starlark({name: [r["cpu_count"], r["memory_kb"], "fast" if name == "precheck" else ""] for name, r in special.items()}) + "\n\n"
            + "COMPILE_REQUESTS = " + starlark(requests) + "\n\n"
            + "# The critical-path compiles that ask for the fast workers (action_sizes_from_log.py).\n"
            + "COMPILE_CLASSES = " + starlark({profile: dict(sorted(CPU_CLASSES[profile].items())) for profile in ("dev", "release")}) + "\n")


def check_classes(buck: str) -> None:
    """Every CPU_CLASSES row names a compile target: a renamed or split crate
    must not silently fall off the fast workers."""
    for profile, targets in CPU_CLASSES.items():
        for target in targets:
            if f'    name = "{target.removesuffix("-harness")}",\n' not in buck:
                raise SystemExit(f"CPU_CLASSES names no target: {profile}/{target} (tools/buck2/action_sizes_from_log.py)")


def check_test_data(buck: str) -> None:
    """Every TEST_DATA row names a test binary: a renamed one must not lose its data."""
    for binary in TEST_DATA:
        if f'    name = "{binary}",\n' not in buck:
            raise SystemExit(f"TEST_DATA names no test binary: {binary} (tools/buck2/sync.py)")


def generate(out_root: pathlib.Path, parts=tuple(generated.PARTS)) -> dict[str, generated.Reads]:
    """Write the named parts' outputs under `out_root`, each only where its
    bytes change; returns what each part read."""
    found = {}
    product_inputs = generated.Reads(ROOT)
    slots = release_product(product_inputs)["runtime_slots"]
    runtime_features = [slot["features"] for slot in slots.values()]
    env = rust_environment.environment(ROOT)
    cargo_home = rust_environment.cargo_home(ROOT, env)
    with tempfile.TemporaryDirectory(prefix="hirsel-sync-cargo-") as temporary:
        offline = rust_environment.private_cargo_environment(
            pathlib.Path(temporary), env, cargo_home, rust_environment.cargo_config(cargo_home),
        )
        meta = metadata(ROOT / "Cargo.toml", offline, cargo_home)
        resolution = Resolution(ROOT, meta, runtime_features)
        if "third-party" in parts:
            found["third-party"] = write_third_party(meta, out_root / "third-party", resolution, offline, cargo_home)
    # Both generators use the same Cargo identities. When only first-party
    # inventory is stale the current third-party output supplies the templates.
    if "first-party" in parts:
        if "third-party" not in parts:
            resolution.load_external((out_root / "third-party/units.json").read_text())
        found["first-party"] = write_first_party(meta, out_root, resolution)
    for reads in found.values():
        for path, digest in product_inputs.files.items():
            reads.note(reads.files, path, digest)
        code_reads(reads)
    return found


def write_first_party(meta: dict, out_root: pathlib.Path, resolution: Resolution) -> generated.Reads:
    global READS
    READS = generated.Reads(ROOT)
    READS.text(out_root / "third-party/units.json")
    cargo_reads(READS, meta, layout=True)
    product = release_product(READS)
    workspace = {p["id"] for p in meta["packages"] if p["id"] in meta["workspace_members"]}
    packages = [{"name": p["name"], "dependencies": [
        {key: (str(pathlib.Path(value).relative_to(ROOT)) if key == "path" and value else value)
         for key, value in dependency.items() if key in ("name", "kind", "path", "req", "uses_default_features")}
        for dependency in p["dependencies"]]} for p in meta["packages"] if p["id"] in workspace]
    contents = {
        "tools/buck2/workspace-metadata.json": json.dumps({"packages": packages}, indent=2, sort_keys=True) + "\n",
        "BUCK": root_buck(meta, resolution),
        "tools/buck2/exec_sizes.bzl": execution_sizes(),
        "tools/buck2/test_sizes.bzl": requests_bzl(json.loads(READS.text(HERE / "test-sizes.json"))),
        "tools/native-toolchain/pins.bzl": native_toolchain_pins(),
        "tools/toolchain-dist/product.bzl": HEADER + "".join(
            f"{name.upper()} = {starlark(product[name], 0)}\n" for name in ("runtime_targets", "hosts")),
    }
    assert set(contents) == set(generated.PARTS["first-party"])
    for path, content in contents.items():
        write(out_root / path, content)
    return READS


def root_buck(meta: dict, resolution: Resolution) -> str:
    buck = resolution.first_party(first_party(meta), starlark)
    check_classes(buck)
    check_test_data(buck)
    policy = json.loads(READS.text(HERE / "production-features.json"))
    declared = {f"{p['name']}/{feature}" for p in meta["packages"]
                if p["id"] in meta["workspace_members"] for feature in p["features"]}
    classified = set(policy["features"])
    if declared != classified:
        raise SystemExit("production feature inventory changed; audit and classify: "
                         + ", ".join(sorted(declared ^ classified)))
    check_production_features(buck, policy, strict=True)
    return buck


def check_production_features(buck: str, policy: dict, strict: bool = False, platform=None) -> list[str]:
    """Audit generated first-party features along normal and build-script edges.

    Audit each target configuration for checked, release and dist. A runtime
    archive's root is its library, so the audit follows the library graph.
    Third-party features are outside this first-party inventory.
    """
    if platform is None:
        platforms = {name for node in ast.walk(ast.parse(buck))
                     if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                     and node.func.id == "cargo_platforms"
                     for name in ast.literal_eval(node.args[0])}
        if platforms:
            return sorted({finding for name in sorted(platforms)
                           for finding in check_production_features(buck, policy, strict, name)})
    if set(policy["features"].values()) - {"test-only", "runtime-option"}:
        raise SystemExit("unknown production feature classification")
    rules = {}
    for statement in ast.parse(buck).body:
        if not isinstance(statement, ast.Expr) or not isinstance(call := statement.value, ast.Call):
            continue
        if not isinstance(call.func, ast.Name) or call.func.id not in {"hirsel_library", "hirsel_binary", "hirsel_build_script"}:
            continue
        try:  # A unit with no variant on this platform; a root or dependency naming it still fails below.
            attrs = {k.arg: configured(k.value, platform) for k in call.keywords
                     if k.arg in {"name", "package_name", "features", "deps", "build_script"}}
        except KeyError: continue
        rules[attrs["name"]] = attrs
    findings, errors = [], []
    for root, exceptions in policy["roots"].items():
        pending, seen, leaks = [root], set(), set()
        while pending:
            name = pending.pop()
            if name in seen:
                continue
            seen.add(name)
            if name not in rules:
                raise SystemExit(f"production feature audit has no first-party target: {name}")
            attrs = rules[name]
            for feature in attrs["features"]:
                key = f"{attrs['package_name']}/{feature}"
                if key not in policy["features"]:
                    raise SystemExit(f"production feature audit has no classification: {key}")
                if policy["features"][key] == "test-only":
                    leaks.add(f"{name}/{feature}")
            for dep in attrs.get("deps", []) + ([attrs["build_script"]] if attrs.get("build_script") else []):
                if dep.startswith("//:") or dep.startswith(":"):
                    pending.append(dep.split(":", 1)[1])
        findings += [f"{root}: {leak}" for leak in sorted(leaks)]
        allowed = set() if strict else set(exceptions)
        errors += [f"{root}: unapproved test feature {leak}" for leak in sorted(leaks - allowed)]
        if not strict:
            errors += [f"{root}: remove resolved feature exception {leak}" for leak in sorted(allowed - leaks)]
    if errors:
        raise SystemExit("production feature audit failed:\n" + "\n".join(errors))
    return findings


def native_toolchain_pins() -> str:
    directory = ROOT / "tools/native-toolchain"
    records = [line.split() for line in READS.text(directory / "llvm-23.lock").splitlines()
               if line and not line.startswith("#")]
    scalars = {row[0]: " ".join(row[1:]) for row in records if row[0] != "deb"}
    def llvm_asset(name):
        sha, size, asset = scalars[name].split()
        return {"url": f"{scalars['asset_pool']}/{asset}", "sha256": sha, "size": int(size)}
    pins = json.loads(READS.text(directory / "native.lock.json"))
    valgrind_runtime = pins.pop("valgrind_runtime")
    link_kit = pins.pop("link_kit")
    return (HEADER + "BOOTSTRAP_LLVM = " + json.dumps(llvm_asset("bootstrap_llvm"), indent=4)
            + "\nSTATIC_LLD = " + json.dumps(llvm_asset("static_lld"), indent=4)
            + "\nVALGRIND_DEBS = " + json.dumps(valgrind_runtime, indent=4)
            + "\nLINK_KIT = " + json.dumps(link_kit, indent=4)
            + "\nNATIVE = " + json.dumps({k: v for k, v in pins.items() if k != "schema"}, indent=4) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--if-stale", action="store_true",
                        help="regenerate only the parts whose outputs or inputs changed since they were generated")
    parser.add_argument("--check", action="store_true",
                        help="regenerate when stale")
    parser.add_argument("--strict-production-features", action="store_true",
                        help="fail on every production test feature, including the explicitly recorded baseline leaks")
    args = parser.parse_args()
    prepare.configure_test_executor(ROOT)
    if not REINDEER.is_file():
        raise SystemExit("run tools/buck2/bootstrap.py first (Reindeer is missing)")
    parts = generated.stale(ROOT) if args.if_stale or args.check else list(generated.PARTS)
    if parts:
        for part, reads in generate(ROOT, parts).items():
            generated.record(ROOT, part, reads)
    if args.strict_production_features:
        check_production_features((ROOT / "BUCK").read_text(),
                                  json.loads((HERE / "production-features.json").read_text()), strict=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
