const TABLE_MARKER: &str = "// Unicode tables generated by core/tools/regex_oracle.rs.\n";

fn ast_kind(kind: &ast::ErrorKind) -> String {
    match kind {
        ast::ErrorKind::FlagDuplicate { .. } => "FlagDuplicate".into(),
        ast::ErrorKind::FlagRepeatedNegation { .. } => "FlagRepeatedNegation".into(),
        ast::ErrorKind::GroupNameDuplicate { .. } => "GroupNameDuplicate".into(),
        ast::ErrorKind::NestLimitExceeded(_) => "NestLimitExceeded".into(),
        _ => format!("{kind:?}"),
    }
}

fn syntax(pattern: &str) -> Result<(), (usize, String)> {
    let parsed = ast::parse::Parser::new()
        .parse(pattern)
        .map_err(|err| (err.span().start.offset, ast_kind(err.kind())))?;
    hir::translate::Translator::new()
        .translate(pattern, &parsed)
        .map(|_| ())
        .map_err(|err| (err.span().start.offset, format!("{:?}", err.kind())))
}

fn literal(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

