#!/usr/bin/env python3
"""Generate cli@1's wide-character table from the pinned EastAsianWidth.txt.

The table lists the scalars whose East_Asian_Width is W or F as merged ranges, with the
Unicode version it was built from. cli@1's version law compares that version with
char.UNICODE_VERSION, so a Unicode upgrade of std fails until this table is regenerated
from the new file (and DIGEST below is updated with it).
"""

import argparse
from hashlib import sha256
from pathlib import Path
import re

TARGET = Path(__file__).resolve().parents[1] / "programs" / "cli" / "width.hirsel"
BEGIN = "// BEGIN generated by core/tools/cli_width_table.py\n"
END = "// END\n"
NOTICE = "// Unicode data is licensed under Unicode-3.0 (https://www.unicode.org/license.txt)."
NAME = "EastAsianWidth.txt"
DIGEST = "a0cf29eacd00cfcaec4381c6b7c281685f18dbb4e7ff82b4076ccb342ca839aa"


def wide_ranges(source):
    ranges = []
    for line in source.splitlines():
        content = line.partition("#")[0].strip()
        if not content:
            continue
        codes, width = (field.strip() for field in content.split(";"))
        if width not in ("W", "F"):
            continue
        low, _, high = codes.partition("..")
        lo, hi = int(low, 16), int(high or low, 16)
        if ranges and ranges[-1][1] + 1 == lo:
            ranges[-1][1] = hi
        else:
            if ranges and lo <= ranges[-1][1]:
                raise ValueError(f"{NAME}: ranges out of order at {codes}")
            ranges.append([lo, hi])
    return ranges


def generate(source):
    version = re.match(r"# EastAsianWidth-(\d+)\.(\d+)\.(\d+)\.txt", source)
    if not version:
        raise ValueError(f"{NAME}: no version line")
    ranges = wide_ranges(source)
    flat = ", ".join(f"0x{bound:05x}" for pair in ranges for bound in pair)
    major, minor, update = version.groups()
    return (
        f"{NOTICE}\n"
        f"const WIDE_VERSION: (u8, u8, u8) = ({major}, {minor}, {update})\n\n"
        f"const WIDE_RANGES: u64 = {len(ranges)}\n\n"
        f"const WIDE: Inline[u32, {2 * len(ranges)}] =[{flat}]\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ucd", type=Path, required=True, help="a directory holding EastAsianWidth.txt")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        data = (args.ucd / NAME).read_bytes()
        actual = sha256(data).hexdigest()
        if actual != DIGEST:
            raise ValueError(f"{NAME}: SHA-256 {actual}, expected {DIGEST}")
        table = generate(data.decode("utf-8"))
        old = TARGET.read_text(encoding="utf-8")
        head, begin, tail = old.partition(BEGIN)
        _, end, rest = tail.partition(END)
        if not begin or not end or BEGIN in rest:
            raise ValueError(f"{TARGET}: expected one generated region")
        new = head + begin + table + end + rest
        if args.write:
            TARGET.write_text(new, encoding="utf-8")
        elif old != new:
            raise ValueError(f"{TARGET}: the generated table differs")
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
