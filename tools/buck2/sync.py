#!/usr/bin/env python3
"""Derive every Buck2 build file from the Cargo workspace.

Cargo manifests and Cargo.lock are the source of truth. This script writes
generated.BUILD_INPUTS, all gitignored:

- `third-party/Cargo.toml` and `third-party/Cargo.lock`: one standalone package
  that depends on every external crate a workspace member names, at the
  version and with the features Cargo resolved for the workspace;
- `third-party/BUCK`, by running the pinned Reindeer over that manifest
  (`third-party/reindeer.toml`, `third-party/fixups/`);
- the root `BUCK`: a library, binary, example, build script and test target
  for every Cargo target of every workspace member;
- the `.bzl` files of measured requests and native pins, and the workspace
  metadata a test reads.

All first-party targets live in the root package, so a crate's source tree in a
compile action keeps its repository layout and `include_str!("../../x")`
reaches files elsewhere in the repository. Compile inputs outside a target's
own directory are found by following literal `include*!` and `#[path]`
references, plus the files an `include_str!(concat!("<prefix>", $arg))` macro
names through the file's string literals.

Generation has two parts, each stamped with exactly what it read
(generated.py): third-party dependency generation reads the Cargo manifests,
Cargo.lock, the Rust toolchain pin, the Reindeer pin, config and fixups;
first-party inventory generation reads the manifests, Cargo's target layout,
the Rust sources it inspects (compile-time includes, `#[path]` modules,
doctests, `proptest!`, the memory guard) and the measurements and pins it renders. Both read this generator's own code.
Either part writes an output only when its bytes change.

Without flags, sync.py regenerates both parts. `--if-stale` regenerates only
the parts whose outputs are missing or edited or whose inputs read differently
since they were generated. `--check` also regenerates stale parts.
"""

