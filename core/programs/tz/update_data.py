#!/usr/bin/env python3
"""Generate the embedded database from the pinned IANA tzdata release."""

import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import tarfile
import tempfile
import urllib.request
import zlib

VERSION = "2026f"
SHA256 = "01b4a91cec5167ed48c11e8ab78f2048cead78ce94b0cafcad0ae8c5a3044d3d"
URL = f"https://data.iana.org/time-zones/releases/tzdata{VERSION}.tar.gz"
SOURCES = (
    "africa", "antarctica", "asia", "australasia", "europe", "northamerica",
    "southamerica", "etcetera", "factory", "backward",
)


def pack(zones):
    entries = sorted((p for p in zones.rglob("*") if p.is_file()), key=lambda p: p.relative_to(zones).as_posix())
    header = bytearray(struct.pack(">I", len(entries)))
    base = 4 + 16 * len(entries)
    names = bytearray()
    for entry in entries:
        name = entry.relative_to(zones).as_posix().encode("ascii")
        if not re.fullmatch(rb"[A-Za-z0-9_+-]+(?:/[A-Za-z0-9_+-]+)*", name):
            raise ValueError(f"unsupported zone name {name!r}")
        names.extend(name)
    payload = bytearray()
    positions = {}
    name_at = base
    for entry in entries:
        name = entry.relative_to(zones).as_posix().encode("ascii")
        data = entry.read_bytes()
        if data[:5] not in (b"TZif2", b"TZif3") or len(data) > 262144:
            raise ValueError(f"unsupported TZif record {name!r}")
        if data not in positions:
            positions[data] = base + len(names) + len(payload)
            payload.extend(data)
        header.extend(struct.pack(">IIII", name_at, len(name), positions[data], len(data)))
        name_at += len(name)
    return bytes(header + names + payload), len(entries), len(positions)


def byte_literal(data):
    return "".join(
        chr(b) if 32 <= b <= 126 and b not in (34, 92) else rf"\x{b:02x}"
        for b in data
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="use an existing copy of the pinned release")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="hirsel-tzdata-") as temp:
        root = Path(temp)
        archive = args.archive or root / "tzdata.tar.gz"
        if args.archive is None:
            with urllib.request.urlopen(URL, timeout=30) as response:
                archive.write_bytes(response.read())
        if hashlib.sha256(archive.read_bytes()).hexdigest() != SHA256:
            raise SystemExit("tzdata archive SHA-256 differs from the pin")
        with tarfile.open(archive, "r:gz") as source:
            if source.extractfile("version").read().decode("ascii").strip() != VERSION:
                raise SystemExit("tzdata version differs from the pin")
            for name in SOURCES:
                (root / name).write_bytes(source.extractfile(name).read())
        zones = root / "zones"
        subprocess.run(["zic", "-b", "slim", "-d", str(zones), *SOURCES], cwd=root, check=True)
        data, names, unique = pack(zones)
    if len(data) > 1048576:
        raise SystemExit("database exceeds the Hirsel decoder's size limit")
    compressed = zlib.compress(data, level=9)
    target = Path(__file__).with_name("data.hirsel")
    target.write_text(
        '// Generated by update_data.py from public-domain IANA tzdata.\n'
        f'fn data_version() -> String {{\n    "{VERSION}"\n}}\n\n'
        f'fn compressed_data() -> Bytes {{\n    b"{byte_literal(compressed)}"\n}}\n',
        encoding="ascii",
    )
    print(f"{VERSION}: {names} names, {unique} TZif records, "
          f"{len(data)} bytes unpacked, {len(compressed)} bytes compressed")


if __name__ == "__main__":
    main()
