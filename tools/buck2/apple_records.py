"""Derive the build inputs and standalone shell recipe arguments for EMB-2."""

import argparse
import json
from pathlib import Path
import re

from generated import write


SOURCE = "tools/native-toolchain/apple-targets.json"
RUST = "crates/hirsel-core-layout/src/apple_records.rs"
STARLARK = "tools/buck2/toolchains/apple.bzl"
VARIANTS = ("macos", "ios", "ios-simulator")
CLIF_FEATURES = {
    "apple-m1": ["has_lse", "has_fp16", "has_dotprod"],
    "apple-a12": ["has_lse", "has_fp16"],
}


class AppleRecords:
    def __init__(self, source):
        document = json.loads(source)
        targets = document["targets"]
        if targets.keys() != set(VARIANTS):
            raise SystemExit(f"{SOURCE}: expected targets {', '.join(VARIANTS)}")
        self.rows = {}
        for name in VARIANTS:
            row = targets[name]
            family, floor = row["family"], row["floor"]
            cpu = document["cpu_by_floor"].get(family, {}).get(floor)
            if cpu not in CLIF_FEATURES:
                problem = "no cpu_by_floor row" if cpu is None else f"unknown CPU {cpu}"
                raise SystemExit(f"{SOURCE}: {name}: {problem} for ({family}, {floor})")
            version = re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", floor)
            if not version:
                raise SystemExit(f"{SOURCE}: {name}: expected a major.minor floor")
            major, minor = map(int, version.groups())
            if major > 65535 or minor > 255:
                raise SystemExit(f"{SOURCE}: {name}: floor is out of Mach-O version range")
            llvm_os = row["llvm_os"]
            environment = row.get("llvm_environment", "")
            # target-lexicon accepts macosx and sim, Clang and LLVM use macos and simulator.
            clif_os = "macosx" if llvm_os == "macos" else llvm_os
            self.rows[name] = {
                **row,
                "llvm_environment": environment,
                "cpu": cpu,
                "cranelift_features": CLIF_FEATURES[cpu],
                "llvm_triple": f"arm64-apple-{llvm_os}{floor}" + (f"-{environment}" if environment else ""),
                "cranelift_triple": f"arm64-apple-{clif_os}{floor}" + ("-sim" if environment else ""),
                "macho_minos": major << 16 | minor << 8,
            }

    def outputs(self):
        message = f"@generated by tools/buck2/sync.py from {SOURCE}; do not edit."
        rust = [f"// {message}", "", "use crate::target::AppleRecord;"]
        for name, row in self.rows.items():
            constant = name.upper().replace("-", "_")
            rust.extend(("", f"pub(super) const {constant}: AppleRecord = AppleRecord {{"))
            for field, value in row.items():
                literal = json.dumps(value, ensure_ascii=False)
                if isinstance(value, list):
                    literal = "&" + literal
                rust.append(f"    {field}: {literal},")
            rust.append("};")
        starlark = json.dumps(self.rows, indent=4, ensure_ascii=False)
        return {RUST: "\n".join(rust) + "\n", STARLARK: f"# {message}\n\nAPPLE_TARGETS = {starlark}\n"}


def sync(root: Path, check: bool) -> None:
    records = AppleRecords((root / SOURCE).read_text())
    stale = []
    for path, content in records.outputs().items():
        output = root / path
        if not check:
            write(output, content)
        elif not output.is_file() or output.read_bytes() != content.encode():
            stale.append(path)
    if stale:
        raise SystemExit("stale Apple target records: " + ", ".join(stale)
                         + "\nrun python3 tools/buck2/sync.py --if-stale")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("variant", choices=VARIANTS)
    parser.add_argument("fields", nargs="+")
    args = parser.parse_args()
    source = Path(__file__).resolve().parents[2] / SOURCE
    record = AppleRecords(source.read_text()).rows[args.variant]
    print(*(record[field] for field in args.fields))


if __name__ == "__main__":
    main()
