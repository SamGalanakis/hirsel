#!/usr/bin/env python3
"""Generate a Hirsel module for an immutable HTTP asset directory."""

import argparse
import gzip
import hashlib
import io
import mimetypes
from pathlib import Path
import subprocess
import sys


def literal(text):
    text.encode('utf-8')
    escaped = []
    for char in text:
        if char in '"\\':
            escaped.append('\\' + char)
        elif ord(char) < 32 or ord(char) == 127:
            escaped.append(f'\\u{{{ord(char):x}}}')
        else:
            escaped.append(char)
    return '"' + ''.join(escaped) + '"'


def byte_literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def gzip_bytes(data):
    destination = io.BytesIO()
    with gzip.GzipFile(filename='', fileobj=destination, mode='wb', mtime=0) as output:
        output.write(data)
    return destination.getvalue()


def fingerprint(path, digest):
    suffix = '-' + digest[:8]
    if path.stem.endswith(suffix):
        return path
    return path.with_name(path.stem + suffix + path.suffix)


def emit_entry(index, path, alias, media_type, formats):
    yield f'fn asset_{index}() -> assets.Entry {{'
    yield f'    let mut path: List[String] = list.with_capacity({len(path.parts)})'
    for part in path.parts:
        yield f'    list.push(mut path, string.from({literal(part)}))'
    yield f'    let mut formats: List[assets.Representation] = list.with_capacity({len(formats)})'
    for coding, data in formats:
        etag = '"' + hashlib.sha256(data).hexdigest() + '"'
        body = f'{coding.lower()}_body'
        yield f'    let {body} = {byte_literal(data)}'
        yield f'    list.push(mut formats, assets.representation({coding}, take {body}, string.from({literal(etag)})))'
    yield f'    assets.Entry(path: take path, fingerprint: string.from({literal(alias.name)}), media_type: string.from({literal(media_type)}), formats: take formats)'
    yield '}'


def emit(root, brotli):
    if not root.is_dir():
        raise ValueError(f'asset directory does not exist: {root}')
    media = mimetypes.MimeTypes(filenames=())
    paths = {}
    entries = []
    for source in sorted(root.rglob('*')):
        if source.is_symlink():
            raise ValueError(f'asset directory contains a symlink: {source.relative_to(root)}')
        if not source.is_file():
            continue
        path = source.relative_to(root)
        data = source.read_bytes()
        alias = fingerprint(path, hashlib.sha256(data).hexdigest())
        for name in (path, alias):
            if name in paths and paths[name] != path:
                raise ValueError(f'asset URL collision: {name}')
            paths[name] = path
        formats = [('Identity', data)]
        compressed = gzip_bytes(data)
        if len(compressed) < len(data):
            formats.append(('Gzip', compressed))
        if brotli is not None:
            compressed = subprocess.run([brotli, '-q', '11', '-c'], input=data, capture_output=True, check=True).stdout
            if len(compressed) < len(data):
                formats.append(('Brotli', compressed))
        media_type = media.guess_type(path.name)[0] or 'application/octet-stream'
        entries.append((path, alias, media_type, formats))

    yield '// Generated by core/tools/http_assets.py.'
    yield ''
    for index, entry in enumerate(entries):
        yield from emit_entry(index, *entry)
        yield ''
    yield 'pub fn manifest() -> assets.Manifest {'
    yield f'    let mut entries: List[assets.Entry] = list.with_capacity({len(entries)})'
    for index in range(len(entries)):
        yield f'    list.push(mut entries, asset_{index}())'
    yield '    assets.manifest(take entries)'
    yield '}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--brotli', metavar='PROGRAM', help='Brotli encoder to run at build time')
    options = parser.parse_args()
    try:
        output = '\n'.join(emit(options.directory, options.brotli))
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.error(str(error))
    print(output)


if __name__ == '__main__':
    sys.exit(main())
