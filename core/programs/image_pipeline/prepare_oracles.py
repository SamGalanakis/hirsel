"""Build the thumbnail law's inputs and independent Pillow oracles."""
import base64
import hashlib
import hmac
import io
from pathlib import Path
import struct

from PIL import Image, ImageOps
import pillow_avif

HERE = Path(__file__).resolve().parent
VECTORS = {}
TARGET = (96, 64)


def encoded(image, fmt, **options):
    out = io.BytesIO()
    image.save(out, fmt, **options)
    return out.getvalue()


def app(marker, value):
    return bytes((255, marker)) + struct.pack(">H", len(value) + 2) + value


def jpeg_exif(image, thumbnail, orientation):
    offset = 44 + 12
    prefix = b"II" + struct.pack("<HI", 42, 8)
    first = struct.pack("<H HHII I", 1, 0x0112, 3, 1, orientation, 26)
    second = struct.pack("<H HHII HHII I", 2, 0x0201, 4, 1, offset,
                         0x0202, 4, 1, len(thumbnail), 0)
    assert len(prefix + first + second) == offset
    return image[:2] + app(0xE1, b"Exif\0\0" + prefix + first + second + thumbnail) + image[2:]


def save(name, content):
    VECTORS[name] = content


def token(value):
    return base64.urlsafe_b64encode(value).rstrip(b"=")


def main():
    source = Image.new("RGB", (288, 192))
    source.putdata([
        (24 + x * 170 // 287, 32 + y * 160 // 191, 42 + (x + y) * 140 // 478)
        for y in range(192) for x in range(288)
    ])
    jpeg = encoded(source, "JPEG", quality=94, subsampling=0)
    webp = encoded(source, "WEBP", lossless=True)
    avif = encoded(source, "AVIF", quality=85, speed=8, subsampling="4:2:0",
                   range="limited", max_threads=1)
    avif_full = encoded(source, "AVIF", quality=85, speed=8, subsampling="4:2:0",
                        range="full", max_threads=1)
    for name, packet in (("jpeg", jpeg), ("webp", webp), ("avif", avif), ("avif-full", avif_full)):
        save(name + ".image", packet)
        image = ImageOps.exif_transpose(Image.open(io.BytesIO(packet))).convert("RGB")
        save(name + ".rgb", image.resize(TARGET, Image.Resampling.LANCZOS).tobytes())

    portrait = source.transpose(Image.Transpose.ROTATE_90)
    primary = encoded(portrait, "JPEG", quality=94, subsampling=0)
    preview = encoded(portrait.resize((64, 96), Image.Resampling.LANCZOS),
                      "JPEG", quality=92, subsampling=0)
    save("exif.jpg", jpeg_exif(primary, preview, 6))
    small = encoded(source.resize((48, 32), Image.Resampling.LANCZOS),
                    "JPEG", quality=92, subsampling=0)
    save("jfxx.jpg", jpeg[:2] + app(0xE0, b"JFXX\0\x10" + small) + jpeg[2:])

    digest = hashlib.sha256(jpeg).digest()
    payload = b"\x01\x00" + digest + struct.pack(">II", *TARGET)
    message = b"/" + token(payload)
    tag = token(hmac.digest(b"fixture-key", message, "sha256"))
    save("signed.path", b"/" + tag + message)
    tampered = payload[:-1] + bytes((payload[-1] ^ 1,))
    save("tampered.path", b"/" + tag + b"/" + token(tampered))
    save("unsigned.path", message)

    rows = ["// Generated by prepare_oracles.py with Pillow, libavif and Python hmac.",
            "fn load(name: String) -> Bytes {"]
    for i, (name, content) in enumerate(sorted(VECTORS.items())):
        value = base64.b64encode(content).decode("ascii")
        start = "    let encoded = if" if i == 0 else "    } else if"
        rows.extend([f'{start} name == "{name}" {{', f'        b"{value}"'])
    rows += ['    } else {', '        fail("unknown thumbnail fixture")', '    }',
             '    let Some(take decoded) = std.base64.decode(encoded) else {',
             '        fail("invalid encoded thumbnail fixture")', '    }',
             '    take decoded', '}', '']
    (HERE / "oracle_fixtures.hirsel").write_text("\n".join(rows))


if __name__ == "__main__":
    main()
