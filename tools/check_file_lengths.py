#!/usr/bin/env python3
"""Check staged source lengths, or maintain the caps of existing long files."""

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys


LIMIT = 1000
HIRSEL_LIMIT = 2000
SUFFIXES = ('.hirsel', '.rs', '.py', '.ts', '.js', '.c', '.h')
RATCHET = 'tools/file_length_ratchet.json'
EXCLUDED_TREES = (
    'third_party/',  # Vendored third-party dependencies.
    'third-party/',  # Vendored headers and generated dependency inputs.
    'vendor/',  # Vendored dependencies.
    'core/langarena/rust/',  # The upstream LangArena Rust suite and its dependencies.
    'editors/tree-sitter-hirsel/data/src/tree_sitter/',  # Tree-sitter's bundled headers.
    'editors/tree-sitter-hirsel/src/tree_sitter/',  # Tree-sitter's bundled headers.
)
EXCLUDED_FILES = {
    'editors/tree-sitter-hirsel/data/src/parser.c',  # Generated by Tree-sitter.
    'editors/tree-sitter-hirsel/src/parser.c',  # Generated by Tree-sitter.
    'core/langarena/layout/graph_inputs.hirsel',  # Generated by layout/generate.py.
    'core/langarena/layout/graph_inputs.rs',  # Generated by layout/generate.py.
    'core/std/tests/regex_corpus.hirsel',  # Generated by core/tools/regex_oracle.rs.
}


def is_source(path):
    return (path.endswith(SUFFIXES) and path not in EXCLUDED_FILES
            and not path.startswith(EXCLUDED_TREES))


def git(root, *args, data=None):
    return subprocess.run(['git', *args], cwd=root, input=data, check=True,
                          stdout=subprocess.PIPE).stdout


def git_paths(root, *args):
    return os.fsdecode(git(root, *args)).split('\0')[:-1]


def snapshot(root, revision, paths):
    """Read selected worktree, index (:0), or commit blobs."""
    if revision is None:
        return {path: file.read_bytes() for path in paths if (file := root / path).is_file()
                and not file.is_symlink()}
    blobs = {}
    batch = []
    for path in sorted(paths):
        spec = f'{revision}:{path}'
        if '\n' in path:
            # The portable batch protocol takes one object request per line.
            result = subprocess.run(['git', 'show', spec], cwd=root, capture_output=True)
            if result.returncode == 0:
                blobs[path] = result.stdout
        else:
            batch.append((path, os.fsencode(spec)))
    if batch:
        data = git(root, 'cat-file', '--batch', data=b'\n'.join(spec for _, spec in batch) + b'\n')
        start = 0
        for path, _ in batch:
            end = data.index(b'\n', start)
            header = data[start:end].split()
            start = end + 1
            if header[-1] != b'missing':
                end = start + int(header[-1])
                if header[1] == b'blob':
                    blobs[path] = data[start:end]
                start = end + 1
    return blobs


def line_count(data):
    return data.count(b'\n') + int(bool(data) and not data.endswith(b'\n'))


def default_limit(path):
    return HIRSEL_LIMIT if path.endswith('.hirsel') else LIMIT


def parse_ratchet(data):
    if data is None:
        return {}
    entries = json.loads(data)
    for path, entry in entries.items():
        file = Path(path)
        if file.is_absolute() or '..' in file.parts or file.as_posix() != path or not is_source(path):
            raise ValueError(f'{RATCHET}: invalid source path {path}')
        if type(entry['lines']) is not int or entry['lines'] <= LIMIT:
            raise ValueError(f'{RATCHET}: invalid cap for {path}')
        if 'reason' in entry and (not isinstance(entry['reason'], str) or not entry['reason'].strip()):
            raise ValueError(f'{RATCHET}: invalid raise reason for {path}')
        if 'raise_revision' in entry and (type(entry['raise_revision']) is not int or entry['raise_revision'] < 1):
            raise ValueError(f'{RATCHET}: invalid raise revision for {path}')
    return entries


def renames(root, *args):
    """New path -> old path for each rename git detects in a diff."""
    fields = git_paths(root, 'diff', '-M', '--name-status', '-z', *args)
    moved = {}
    index = 0
    while index < len(fields):
        status = fields[index]
        if status.startswith(('R', 'C')):
            if status.startswith('R'):
                moved[fields[index + 2]] = fields[index + 1]
            index += 3
        else:
            index += 2
    return moved


def check_transition(root, before, after, paths, moved=None):
    """`moved` maps a renamed path to its old path, whose length and cap it keeps."""
    moved = moved or {}
    changed = {path for path in paths if is_source(path)}
    if not changed and RATCHET not in paths:
        return True
    selected = changed | {RATCHET}
    previous = snapshot(root, before, selected)
    current = snapshot(root, after, selected)
    old = parse_ratchet(previous.get(RATCHET))
    new = parse_ratchet(current.get(RATCHET))
    if RATCHET in previous and RATCHET not in current:
        print(f'{RATCHET}: keep the file even when every cap has been removed.', file=sys.stderr)
        return False

    adjusted = {path for path in old.keys() | new.keys() if old.get(path) != new.get(path)}
    previous.update(snapshot(root, before, (adjusted - changed) | {moved[path] for path in changed if path in moved}))
    current.update(snapshot(root, after, adjusted - changed))
    ok = True
    for path in sorted(changed | adjusted):
        source = moved.get(path, path)
        prior = line_count(previous.get(source, b''))
        lines = line_count(current.get(path, b''))
        old_entry = old.get(path, old.get(source, {}))
        new_entry = new.get(path, {})
        baseline = default_limit(path)
        old_cap = max(baseline, old_entry.get('lines', baseline))
        new_cap = max(baseline, new_entry.get('lines', baseline))
        limit = min(old_cap, new_cap, max(baseline, prior))
        explicit_raise = (new_cap > old_cap
                          or new_entry.get('raise_revision', 0) > old_entry.get('raise_revision', 0))
        # Existing Hirsel entries may predate the higher default.
        raised = (after is not None and path in old and path in changed and explicit_raise
                  and LIMIT < prior < new_cap == lines and new_cap > baseline and 'reason' in new_entry)
        if raised:
            limit = new_cap
        elif new_cap > old_cap:
            if RATCHET not in previous and new_cap == prior == lines:
                limit = new_cap
            else:
                print(f'{RATCHET}: put the growth of {path} and its --raise entry with a lane '
                      'reason in the same commit.', file=sys.stderr)
                ok = False
        if lines > limit:
            print(f'{path}: {lines:,} lines, limit {limit:,}. Split it into a sibling module.',
                  file=sys.stderr)
            ok = False
    return ok


def check_staged(root):
    paths = git_paths(root, 'diff', '--cached', '--no-renames', '--name-only', '-z')
    return check_transition(root, 'HEAD', ':0', paths, renames(root, '--cached'))


def check_changed(root):
    """Check each branch commit, the index, and the remaining worktree changes."""
    base = git(root, 'merge-base', 'HEAD', 'origin/main').decode().strip()
    commits = git(root, 'rev-list', '--reverse', '--first-parent', f'{base}..HEAD').splitlines()
    for commit in commits:
        revision = commit.decode()
        parent = revision + '^1'
        paths = git_paths(root, 'diff', '--no-renames', '--name-only', '-z', parent, revision)
        if not check_transition(root, parent, revision, paths, renames(root, parent, revision)):
            return False
    if not check_staged(root):
        return False
    paths = git_paths(root, 'diff', '--no-renames', '--name-only', '-z')
    paths += git_paths(root, 'ls-files', '--others', '--exclude-standard', '-z')
    return check_transition(root, ':0', None, paths)


def write_ratchet(root, entries):
    (root / RATCHET).write_text(json.dumps(entries, indent=2, sort_keys=True) + '\n')


def update_ratchet(root, entries):
    lowered = {}
    for path, data in snapshot(root, None, entries).items():
        lines = min(entries[path]['lines'], line_count(data))
        if lines > default_limit(path):
            lowered[path] = dict(entries[path], lines=lines)
    return lowered


def main(root):
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--update-ratchet', action='store_true', help='lower caps using worktree lengths')
    modes.add_argument('--raise', dest='raise_cap', nargs=2, metavar=('FILE', 'LINES'),
                       help='raise the limit from the file length in HEAD and record the lane reason')
    parser.add_argument('--reason', help='lane requesting the raise')
    args = parser.parse_args()
    if args.reason is not None and not args.raise_cap:
        parser.error('--reason requires --raise')
    if not args.update_ratchet and not args.raise_cap:
        return 0 if check_staged(root) else 1

    entries = parse_ratchet((root / RATCHET).read_bytes())
    if args.update_ratchet:
        entries = update_ratchet(root, entries)
    else:
        file, lines = args.raise_cap
        path = Path(file).as_posix()
        if not args.reason or not args.reason.strip():
            parser.error('--raise requires --reason with the lane name')
        if path not in entries:
            parser.error(f'{path} has no existing cap to raise')
        try:
            lines = int(lines)
        except ValueError:
            parser.error('LINES must be an integer')
        prior = line_count(snapshot(root, 'HEAD', {path}).get(path, b''))
        if prior <= LIMIT:
            parser.error(f'{path} must exceed {LIMIT:,} lines in HEAD to raise its limit')
        threshold = max(prior, default_limit(path))
        if lines <= threshold:
            parser.error(f'LINES must exceed {threshold:,}')
        # A raise can set a stale cap to the same or a lower number. Record a
        # fresh revision so an ordinary cap update cannot authorize growth.
        entries[path] = {'lines': lines, 'reason': args.reason.strip(),
                         'raise_revision': entries[path].get('raise_revision', 0) + 1}
    write_ratchet(root, entries)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main(Path(__file__).resolve().parents[1]))
    except (OSError, ValueError, TypeError, KeyError, AttributeError, subprocess.CalledProcessError) as error:
        sys.exit(f'file length check: {error}')
